-- تدقيق استشهادات `lesson_citations` — الصفوف الخمسة الأخيرة من صنف `source_type='book'`
-- (ج-٢٢٥): صفوف «تخريج حديث مصنَّف كتابًا» التي أُجِّل حسمها في ج-٢٢٤ لحاجتها قرارًا بنيويًّا.
--
-- ═══ القرار البنيوي المتَّخذ (على غرار معالجة قرارات المجمع في ج-٢٢٣) ═══
-- 1) `source_type` يبقى `book`: القيم المسموحة (book / scholar_verbal / fatwa_body /
--    website / manuscript) ليس فيها قيمة تصف «تخريج حديث»، وأقربها إلى الواقع أن
--    الاستشهاد هنا هو بكتابٍ حديثيّ مطبوع (الصحيحان) بموضع محدَّد منه — فهو `book` حقًّا.
-- 2) الفجوة الحقيقية كانت غياب «مستند قابل للنقر»، فعولجت بربط كل صفٍّ **بصفحة الحديث
--    نفسه** على المكتبة الشاملة (لا ببطاقة الكتاب فقط)، وهو أدقّ من الخيار الذي اقتُرح
--    في ج-٢٢٤ («بطاقة الصحيح المعني»)، وأنفع للقارئ.
-- 3) الطبعتان المعتمدتان مطابقتان لترقيم الاستشهادات نفسها: صحيح البخاري **ط السلطانية**
--    (shamela.ws/book/1681) وصحيح مسلم **ت محمد فؤاد عبد الباقي** (shamela.ws/book/1727).
-- 4) حين يذكر الاستشهاد مصدرين (البخاري ومسلم) يُربط **بالمصدر المذكور أوّلًا في نصّه**،
--    التزامًا بترتيب النصّ نفسه بدل ترجيح خارجي؛ ورقم الطرف الآخر مُتحقَّق منه كذلك
--    وموثَّق في تعليقات هذا الملف.
--
-- كل رقم حديث أدناه تُحقِّق منه بقراءة نصّ الحديث على الصفحة المعنيَّة (لا بمطابقة رقم مجرَّد)،
-- ومطابقته لنصّ الدرس المستشهِد به.
-- idempotent: كل عبارة مقيَّدة بالنصّ الأصلي، فإعادة التشغيل لا تغيّر شيئًا بعد أول تطبيق.
--
-- ⚠️ لم يُطبَّق هذا الملف على القاعدة الحيّة في دورة إنشائه — لنفس عائق ج-٢٢٢/ج-٢٢٣/ج-٢٢٤،
--    وقد أُعيد التحقُّق منه في هذه الدورة: `artifacts/majalis/.env.local` يحوي
--    `VITE_SUPABASE_URL` و`VITE_SUPABASE_ANON_KEY` فقط (يقرأ ولا يكتب؛ RLS تمنع UPDATE
--    للدور المجهول)، ولا `SUPABASE_SERVICE_ROLE_KEY` ولا `DATABASE_URL`، ولا psql/supabase CLI.
--    يُطبَّق يدويًّا في SQL Editor. صفوفه **مستقلّة تمامًا** عن صفوف `batch7`/`batch8`/`batch9`
--    المعلَّقة (لا تقاطع في نصّ الاستشهاد)، فترتيب التطبيق بينها لا يهمّ.
BEGIN;

-- ═══ أ) ربط بلا أي تغيير في النصّ (الترقيم مُتحقَّق مطابق) ═══

-- 1) «صحيح البخاري (50) وصحيح مسلم (9) — حديث جبريل عليه السلام»
--    (درس: أركان الإسلام والإيمان: الأساس الذي يبدأ منه كل شاب مسلم)
--    البخاري 50: ج1 ص19، «باب سؤال جبريل النبي ﷺ عن الإيمان والإسلام» — عن أبي هريرة:
--    «كان النبي ﷺ بارزًا يومًا للناس فأتاه جبريل فقال: ما الإيمان؟...». ✔
--    ومسلم 9: ص39، «باب بيان الإيمان والإسلام والإحسان» — عن أبي هريرة كذلك بنفس القصة
--    (shamela.ws/book/1727/66)، فالرقمان صحيحان معًا وعن الصحابي نفسه. رُبط بالبخاري (المذكور أوّلًا).
UPDATE lesson_citations SET url='https://shamela.ws/book/1681/96'
 WHERE source_type='book' AND url IS NULL
   AND citation='صحيح البخاري (50) وصحيح مسلم (9) — حديث جبريل عليه السلام';

-- 2) «صحيح البخاري (6094) وصحيح مسلم (2607)»
--    (درس: ضوابط شرعية للتعامل مع الإنترنت ووسائل التواصل الاجتماعي)
--    البخاري 6094: ص25، «باب قول الله تعالى ﴿يا أيها الذين آمنوا اتقوا الله وكونوا مع
--    الصادقين﴾» — عن ابن مسعود: «إن الصدق يهدي إلى البر...». ✔ وهو نفس ما نسبه الدرس إليه
--    حرفًا («وأصله في صحيح البخاري 6094 بلفظ: إن الصدق يهدي إلى البر»).
--    ومسلم 2607: ص2013، «باب قبح الكذب وحسن الصدق وفضله» — وفي روايته الثانية (105) اللفظ
--    الذي نقله الدرس بعينه: «عليكم بالصدق... وإياكم والكذب، فإن الكذب يهدي إلى الفجور...»
--    (shamela.ws/book/1727/6574). فنسبة الدرس للفظ صحيحة كذلك. رُبط بالبخاري (المذكور أوّلًا).
UPDATE lesson_citations SET url='https://shamela.ws/book/1681/9128'
 WHERE source_type='book' AND url IS NULL
   AND citation='صحيح البخاري (6094) وصحيح مسلم (2607)';

-- 3) «صحيح البخاري، كتاب فضائل القرآن، رقم 5027»
--    (درس: مهارات فهم النصوص الشرعية: دلالات الألفاظ عند الأصوليين — قسم «فضل تعلم القرآن وتعليمه»)
--    البخاري 5027: ص192، «باب خيركم من تعلم القرآن وعلمه» من **كتاب فضائل القرآن** — عن
--    عثمان بن عفان: «خيركم من تعلم القرآن وعلمه». ✔ مطابق للرقم والكتاب والباب ولنصّ الدرس.
UPDATE lesson_citations SET url='https://shamela.ws/book/1681/7490'
 WHERE source_type='book' AND url IS NULL
   AND citation='صحيح البخاري، كتاب فضائل القرآن، رقم 5027';

-- 4) «صحيح مسلم، كتاب العلم، رقم 2670»
--    (درس: الوسطية في الإسلام وذم الغلو والتنطع)
--    مسلم 2670: ص2055، «٤ - باب هلك المتنطعون»، وهو ضمن «٤٧ - كتاب العلم» (ترويسة الكتاب
--    على shamela.ws/book/1727/6710) — عن ابن مسعود: «هلك المتنطعون» قالها ثلاثًا. ✔
--    مطابق للرقم واسم الكتاب معًا ولموضوع الدرس.
UPDATE lesson_citations SET url='https://shamela.ws/book/1727/6719'
 WHERE source_type='book' AND url IS NULL
   AND citation='صحيح مسلم، كتاب العلم، رقم 2670';

-- ═══ ب) إتمام ترقيم ناقص + ربط (تعديل نصّ واحد) ═══

-- 5) «صحيح البخاري وصحيح مسلم — عن ابن عباس رضي الله عنهما (حديث الأحرف السبعة، متفق عليه)»
--    (درس: التعريف بعلم القراءات — قسم «دليلها من السنة»)
--    كان الاستشهاد الوحيد في الصنف كله **بلا رقم حديث أصلًا**، فتعذَّر على القارئ بلوغ الموضع.
--    وُقِف على الحديث بنصّه في الصحيحين معًا كما نقله الدرس حرفًا:
--    • البخاري 4991: ص184، «باب أنزل القرآن على سبعة أحرف» (كتاب فضائل القرآن) — عن ابن عباس:
--      «أقرأني جبريل على حرف فراجعته فلم أزل أستزيده ويزيدني حتى انتهى إلى سبعة أحرف». ✔
--    • ومسلم 819: ص561، «(٤٨) باب بيان أن القرآن على سبعة أحرف وبيان معناه» — عن ابن عباس
--      بنفس اللفظ (shamela.ws/book/1727/1832). ✔ فوصف الدرس له بـ«متفق عليه» صحيح.
--    ⇒ أُضيف الرقمان إلى نصّ الاستشهاد (بلا تغيير في النسبة ولا في وصف «متفق عليه»)،
--      ورُبط بالبخاري المذكور أوّلًا. **موسوم في needs-post-review.jsonl** لأن إضافة الترقيم
--      اجتهاد تحريري مني لا نقل حرفيّ من نصّ الاستشهاد الأصلي.
UPDATE lesson_citations
   SET citation='صحيح البخاري (4991) وصحيح مسلم (819) — عن ابن عباس رضي الله عنهما (حديث الأحرف السبعة، متفق عليه)',
       url='https://shamela.ws/book/1681/7440'
 WHERE source_type='book'
   AND citation='صحيح البخاري وصحيح مسلم — عن ابن عباس رضي الله عنهما (حديث الأحرف السبعة، متفق عليه)';

COMMIT;

