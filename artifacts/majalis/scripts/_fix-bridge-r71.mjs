const CAP = 35;
const contents = Object.fromEntries(
  files.map((f) => [f, fs.readFileSync(path.join(LIB, f), "utf8")]),
);

function combined() {
  return files.map((f) => contents[f]).join("");
}

function counts() {
  const c = Object.fromEntries(POOL.map((p) => [p, 0]));
  const text = combined();
  for (const p of POOL) {
    let idx = 0;
    while ((idx = text.indexOf(p, idx)) !== -1) {
      c[p]++;
      idx += p.length;
    }
  }
  return c;
}

function maxFreq(c) {
  let max = 0;
  let top = "";
  for (const p of POOL) {
    if ((c[p] || 0) > max) {
      max = c[p];
      top = p;
    }
  }
  return { max, top };
}

let replaced = 0;
for (let pass = 0; pass < 500; pass++) {
  const c = counts();
  const { max, top } = maxFreq(c);
  if (max <= CAP) break;

  let done = false;
  for (const f of files) {
    const text = contents[f];
    const idx = text.indexOf(top);
    if (idx === -1) continue;
    const alt = POOL.filter((p) => p !== top && !text.includes(p) && (c[p] || 0) < CAP).sort(
      (a, b) => (c[a] || 0) - (c[b] || 0),
    )[0];
    if (!alt) continue;
    contents[f] = text.slice(0, idx) + alt + text.slice(idx + top.length);
    replaced++;
    done = true;
    break;
  }
  if (!done) break;
}

for (const f of files) fs.writeFileSync(path.join(LIB, f), contents[f]);
const final = maxFreq(counts());
