def apply_fixes(rows):
    by_id = {r['id']: r for r in rows}
    out = []
    for rid, old, new, kind, why in FIXES:
        row = by_id.get(rid)
        if row is None:
            sys.exit(f"خطأ: الصفُّ {rid} ليس في المدخلات.")
        body = row['body']
        n = body.count(old)
        if n != 1:
            sys.exit(f"خطأ: النصُّ القديم ورد {n} مرّةً في {rid} — لا مرّةً واحدة.")
        out.append((row, body.replace(old, new), kind, why))
    return out


def verify(fixed) -> int:
    """يعرض كلَّ نصٍّ جديدٍ على بوابة الاستشهاد القرآني."""
    total = bad = 0
    for row, new, kind, _ in fixed:
        for res in vq.check(new):
            total += 1
            st = res['status']
            ok = st in ('OK', 'OK_IMLAI')
            if st == 'NO_TAG':
                ok, st = False, 'NO_TAG (بقي بلا وسم)'
            bad += not ok
            print(f"  {'✔' if ok else '✘'} [{kind}] {st:<18} {res['quote'][:60]}")
    print(f"\n=== بوابةُ الاستشهاد: {total - bad}/{total} سليم")
    return 1 if bad else 0


def sql_escape(s: str) -> str:
    return s.replace("'", "''")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument('rows')
    ap.add_argument('--sql')
    ap.add_argument('--table', default='sharia_rulings')
    ap.add_argument('--verify', action='store_true')
    a = ap.parse_args()

    rows = json.load(sys.stdin if a.rows == '-' else open(a.rows, encoding='utf8'))
    fixed = apply_fixes(rows)
    rc = verify(fixed)
    if a.verify and not a.sql:
        return rc
    if rc:
        sys.exit('خطأ: البوابةُ لم تُجتَز — لم يُكتَب SQL.')
    if a.sql:
        with open(a.sql, 'w', encoding='utf8') as f:
            f.write('-- حسمُ ما تعذَّر على `locate-quran-quotes.py` في sharia_rulings:\n'
                    '-- مقتبَسٌ متعدِّدُ الموضع، وحذفٌ من وسط آيةٍ بلا علامة، واسمُ\n'
                    '-- سورةٍ وُضع بين قوسي الآية خطأً. الحُجّةُ لكلِّ صفٍّ في\n'
                    '-- scripts/gen-sharia-quran-quote-fixes.py (حقل why).\n'
                    'BEGIN;\n')
            for row, new, kind, _ in fixed:
                f.write(f"-- [{kind}] {row['title'][:70]}\n"
                        f"UPDATE {a.table} SET body = '{sql_escape(new)}'\n"
                        f"  WHERE id = '{row['id']}';\n")
            f.write('COMMIT;\n')
        print(f"=== كُتب SQL: {a.sql}")
    return 0


if __name__ == '__main__':
    sys.exit(main())
