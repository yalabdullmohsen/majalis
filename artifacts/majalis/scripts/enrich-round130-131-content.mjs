function makeRoundTopics({ domains, topics }) {
  return domains.flatMap((domain, domainIndex) =>
    topics.map((topic, topicIndex) => ({
      ...domain,
      ...topic,
      level: ["سهل", "متوسط", "متوسط", "صعب", "سهل"][topicIndex],
      category: `${topic.title} في ${domain.section}`,
      reference: domain.references[(domainIndex + topicIndex) % domain.references.length],
    })),
  );
}

function makeQuizItems({ start, topics }) {
  const explanation =
    "الإجابة الصحيحة تجمع بين فهم النص، ومراعاة مقصده، وتنزيله على العمل اليومي بغير غلو ولا تفريط.";
  return topics.map((topic, index) => ({
    id: String(start + index),
    section: topic.section,
    category: topic.category,
    level: topic.level,
    question: `ما العبارة الأدق في ${topic.category}؟`,
    answer: `${topic.meaning}، مع التنبيه إلى أن العلم النافع يربط الاعتقاد والعبادة والخلق بعمل ظاهر منضبط. ${commonTopicTail}`,
    explanation,
    reference: topic.reference,
  }));
}

function makeQaItems({ start, topics }) {
  return topics
    .filter((_, index) => index % 5 !== 4)
    .map((topic, index) => {
      const [category_id, cat_name, cat_slug] = topic.qa;
      return {
        id: String(start + index),
        question: `كيف يطبّق المسلم معنى ${topic.title} في باب ${topic.section}؟`,
        answer: `تطبيقه أن يبدأ المسلم بتصحيح القصد، ثم يعمل بأن ${topic.meaning}. ويوازن بين امتثال النص وحفظ الحقوق والرفق بالخلق، فلا يجعل المعرفة شعارا بلا أثر، ولا ينزل الحكم على الأعيان بلا تحقق وسؤال للراسخين.`,
        category_id,
        ruling_type: index % 3 === 0 ? "أصل شرعي معتبر" : index % 3 === 1 ? "أدب واجب في مواضعه" : "توجيه تربوي مؤكد",
        reference: topic.reference,
        cat_name,
        cat_slug,
      };
    });
}

function makeFawaidItems({ topics }) {
  return topics
    .filter((_, index) => index % 2 === 0)
    .slice(0, 25)
    .map((topic, index) => ({
      text: `من فقه ${topic.category} أن ${topic.meaning}، وأن ثمرة العلم تظهر في إخلاص النية وحفظ اللسان والحقوق وإصلاح السلوك. وهذه فائدة محررة للتذكير والمحاسبة، تقرأ مع مصادرها ولا تجعل بديلا عن الفتوى المفصلة عند النوازل.`,
      category: index % 5 === 0 ? topic.fawaidCategory : index % 2 === 0 ? "تزكية" : topic.fawaidCategory,
      source: topic.reference,
      author_name: index % 2 === 0 ? "أهل العلم" : "محررو مجالس العلم",
    }));
}

