function roundTopics() {
  return domains.flatMap((domain, domainIndex) =>
    topicSets.map(([title, meaning], topicIndex) => ({
      ...domain,
      category: `${title} في ${domain.section}`,
      level: levels[topicIndex],
      title,
      meaning,
      reference: domain.references[(domainIndex + topicIndex) % domain.references.length],
    })),
  );
}

function makeQuizItems({ start }) {
  const suffix =
    " وهذا جواب تعليمي يقرر أصلا عاما، ولا يغني عن سؤال أهل العلم عند النوازل والوقائع الخاصة.";
  const explanation =
    "يضبط المتعلم الباب حين يجمع بين الدليل الصحيح وفهم العلماء وحال المكلف، ثم يجعل ثمرة العلم عملا راشدا لا شعارا مجردا.";
  return roundTopics().map((topic, index) => ({
    id: String(start + index),
    section: topic.section,
    category: topic.category,
    level: topic.level,
    question: `ما أثر أصل ${topic.title} في تهذيب باب ${topic.section}؟`,
    answer: `${topic.meaning}، مع حفظ حدود النصوص ومقاصد الشرع والتثبت من تفاصيل الواقعة قبل الحكم.${suffix}`,
    explanation,
    reference: topic.reference,
  }));
}

function makeQaItems({ start }) {
  const suffix =
    " وهذا جواب للتعليم والتذكير، ولا يطبق على الأعيان إلا بعد معرفة الشروط والموانع وسؤال أهل العلم.";
  return roundTopics()
    .slice(0, 40)
    .map((topic, index) => {
      const [category_id, cat_name, cat_slug] = qaCategories[topic.qaKey];
      return {
        id: String(start + index),
        question: `كيف يعمل المسلم بأصل ${topic.title} في باب ${topic.section} دون غلو؟`,
        answer: `يعمل به على بصيرة فيفهم معناه: ${topic.meaning}. ثم يزنه بالدليل والقدرة والمصلحة، ويجتنب تحويل الأصل إلى اتهام للناس أو تفريط في الحقوق.${suffix}`,
        category_id,
        ruling_type: index % 3 === 0 ? "أصل معتبر" : index % 3 === 1 ? "مشروع بضوابطه" : "تفصيل بحسب الحال",
        reference: topic.reference,
        cat_name,
        cat_slug,
      };
    });
}

