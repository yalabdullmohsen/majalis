  const items = readTsExport(pmPath, "PROPHETIC_MEDICINE_ITEMS");
  let bodyCount = 0;
  let benefitCount = 0;
  for (const item of items) {
    if (item.body.length < PM_BODY_MIN) {
      const neu = enrichPmBody(item.body, item);
      if (content.includes(`body:\n      "${item.body}"`)) {
        content = content.replace(`body:\n      "${item.body}"`, `body:\n      "${neu}"`);
        bodyCount++;
      } else if (content.includes(`body: "${item.body}"`)) {
        content = content.replace(`body: "${item.body}"`, `body: "${neu}"`);
        bodyCount++;
      }
    }
    for (const b of item.benefits) {
      if (b.length < PM_BENEFIT_MIN) {
        const neu = enrichPmBenefit(b);
        if (content.includes(`"${b}"`)) {
          content = content.replace(`"${b}"`, `"${neu}"`);
          benefitCount++;
        }
      }
    }
  }
  fs.writeFileSync(pmPath, content, "utf8");
  return { bodyCount, benefitCount };
