function clean(text) {
  let out = text;
  for (const re of STRIP_PATTERNS) {
    out = out.replace(re, "");
  }
  for (const re of SECOND_PASS) {
    out = out.replace(re, "");
  }
  // تنظيف نهايات مقطوعة
  out = out.replace(/\s+[؛،]\s*$/, "");
  if (out && !/[.!?»"]$/.test(out.trim())) out = out.trim() + ".";
  out = out.replace(/\s+\.\s*$/, ".");
  out = out.replace(/\.{2,}/g, ".");
  out = out.replace(/\s{2,}/g, " ");
  out = out.trim();
  if (EXACT_FIXES.has(out)) out = EXACT_FIXES.get(out);
  return out;
}

let total = 0;
for (const rel of FILES) {
  const abs = path.join(ROOT, rel);
  let src = readFileSync(abs, "utf-8");
  const before = src;
  // تنظيف حقول desc/description/text داخل string literals
  src = src.replace(
    /((?:desc|description|text):\s*")([^"]*)(")/g,
    (_m, pre, body, post) => {
      const cleaned = clean(body);
      if (cleaned !== body) total++;
      return pre + cleaned + post;
    },
  );
  if (src !== before) {
    writeFileSync(abs, src, "utf-8");
    console.log(`✓ نظّف ${rel}`);
  }
}
console.log(`\nتم تنظيف ${total} حقلًا.`);
