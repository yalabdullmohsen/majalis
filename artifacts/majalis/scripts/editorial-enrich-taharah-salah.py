def src(pair, ref: str) -> dict:
    return {"book": pair[0], "author": pair[1], "ref": ref}


def apply_editorial(lesson: dict, book: dict, chapter: dict, payload: dict) -> None:
    title = payload["title"]
    summary = payload["summary"]
    preferred = payload["preferred"]
    evidence = payload["evidence"]
    practical = payload["practical"]
    lesson["title"] = title
    lesson["summary"] = summary
    lesson["preferred"] = preferred
    lesson["madhhabNotes"] = preferred
    lesson["evidence"] = evidence
    lesson["practicalSummary"] = practical
    lesson["definition"] = summary.split(".")[0].strip() + "."
    lesson["ruling"] = preferred
    lesson["status"] = "published"
    lesson["needsReview"] = False
    lesson["notes"] = "مثال تعليمي وفق المذهب الحنبلي، وليس فتوى شخصية لحالة معيّنة."
    lesson["sources"] = [
        src(ZAD, f"{book.get('title','')}، {chapter.get('title','')}"),
        src(RAWD, f"{book.get('title','')}، {chapter.get('title','')}"),
        src(MUGHNI, title),
    ]
    bab = (chapter.get("title") or "").replace("باب ", "")
    lesson["keywords"] = [bab, "مثال تطبيقي", "فقه", "حنبلي"]


def write_audit(books: list[dict], updated: int) -> None:
    rows = []
    total = ex = generic = 0
    for b in books:
        nl = 0
        e = 0
        for ch in b.get("chapters") or []:
            for l in ch.get("lessons") or []:
                nl += 1
                total += 1
                if "mithal-tatbiqi" in (l.get("id") or ""):
                    e += 1
                    ex += 1
                    if (l.get("summary") or "").startswith("مثال تعليمي لباب"):
                        generic += 1
        rows.append((b.get("title") or b["id"], len(b.get("chapters") or []), nl, e))

    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    lines = [
        "# تدقيق محتوى الفقه",
        "",
        f"- التاريخ: {now}",
        f"- الجولة: مراجعة تحريرية لأمثلة الطهارة والصلاة",
        f"- إجمالي المسائل: {total} | الأمثلة التطبيقية: {ex}",
        f"- أمثلة حُدّثت تحريريًا هذه الجولة: {updated}",
        f"- أمثلة قالبية متبقية (مثال تعليمي لباب…): {generic}",
        "",
        "| الكتاب | الأبواب | المسائل | أمثلة |",
        "|---|---:|---:|---:|",
    ]
    for title, nch, nl, e in rows:
        lines.append(f"| {title} | {nch} | {nl} | {e} |")
    lines += [
        "",
        "## مؤجّل خارج الكتالوج العام",
        "",
        "- لباس الشهرة المعاصر.",
        "- الشبهات الغذائية المعاصرة.",
        "- نوازل الجهاد المعاصرة.",
        "- زيارة النساء للقبور (تحرير مستقل).",
        "",
        "## المنهج",
        "",
        "- تعليمي حنبلية المصدر (زاد / روض / مغني).",
        "- الأمثلة للتصور الفقهي لا للإفتاء الشخصي.",
        "- `needsReview` لا يُعرض للمستخدم.",
        "",
    ]
    AUDIT_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    data = json.loads(BOOKS_PATH.read_text(encoding="utf-8"))
    books = data["books"]
    updated = 0
    missing = []
    for book in books:
        if book["id"] not in {"taharah", "salah"}:
            continue
        for chapter in book.get("chapters") or []:
            key = f"{book['id']}/{chapter['id']}"
            payload = EDITORIAL.get(key)
            lesson = next(
                (l for l in (chapter.get("lessons") or []) if "mithal-tatbiqi" in (l.get("id") or "")),
                None,
            )
            if not lesson:
                missing.append(key + ":no-lesson")
                continue
            if not payload:
                missing.append(key + ":no-editorial")
                continue
            apply_editorial(lesson, book, chapter, payload)
            updated += 1

    BOOKS_PATH.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    write_audit(books, updated)
    print(json.dumps({"updated": updated, "missing": missing, "audit": AUDIT_PATH.name}, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
