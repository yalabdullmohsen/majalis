function loadQuestions() {
  const src = fs.readFileSync(SEED_PATH, "utf8");
  const match = src.match(
    /export const DEMO_QUIZ_QUESTIONS: QuizQuestion\[\] = (\[[\s\S]*\]);/
  );
  if (!match) throw new Error("Could not parse DEMO_QUIZ_QUESTIONS");
  const questions = eval(match[1]);
  return { src, questions };
}

function apply() {
  const { src, questions } = loadQuestions();
  let answersFixed = 0;
  let explanationsFixed = 0;

  for (const q of questions) {
    if (q.answer && q.answer.length < 40 && ANSWER_BY_ID[q.id]) {
      q.answer = ANSWER_BY_ID[q.id];
      answersFixed++;
    }
    if (q.explanation && q.explanation.length < 60 && EXPLANATION_BY_ID[q.id]) {
      q.explanation = EXPLANATION_BY_ID[q.id];
      explanationsFixed++;
    }
  }

  const existingIds = new Set(questions.map((q) => q.id));
  let added = 0;
  for (const nq of NEW_QUESTIONS) {
    if (!existingIds.has(nq.id)) {
      questions.push(nq);
      added++;
    }
  }

  const header = src.slice(0, src.indexOf("export const DEMO_QUIZ_QUESTIONS"));
  const footer = "\n";
  const body = `export const DEMO_QUIZ_QUESTIONS: QuizQuestion[] = ${JSON.stringify(questions, null, 2)};\n`;
  fs.writeFileSync(SEED_PATH, header + body + footer, "utf8");

  return { answersFixed, explanationsFixed, added, total: questions.length };
}

function verify() {
  const { questions } = loadQuestions();
  const shortAnswers = questions.filter((q) => q.answer && q.answer.length < MIN_ANSWER);
  const shortExplanations = questions.filter(
    (q) => q.explanation && q.explanation.length < MIN_EXPLANATION
  );
  const missing = Object.keys(ANSWER_BY_ID).filter((id) => {
    const q = questions.find((x) => x.id === id);
    return q && q.answer.length < MIN_ANSWER;
  });

  console.log("Total questions:", questions.length);
  console.log(`Short answers (<${MIN_ANSWER}):`, shortAnswers.length);
  console.log(`Short explanations (<${MIN_EXPLANATION}):`, shortExplanations.length);
  if (missing.length) {
    console.log("Missing expansions for mapped IDs:", missing.join(", "));
  }
  if (shortAnswers.length) {
    shortAnswers.slice(0, 5).forEach((q) =>
      console.log(`  ${q.id}: ${q.answer.length} chars — ${q.answer.slice(0, 40)}...`)
    );
  }
  return shortAnswers.length === 0 && shortExplanations.length === 0;
}

const args = process.argv.slice(2);
if (args.includes("--verify")) {
  const ok = verify();
  process.exit(ok ? 0 : 1);
}
if (args.includes("--apply")) {
  const r = apply();
  console.log("Applied:", r);
  verify();
} else {
  verify();
  console.log("\nRun with --apply to write changes.");
}
