const levels = ["متوسط", "سهل", "متوسط", "صعب", "سهل"];

function roundTopics() {
  return domains.flatMap((domain, domainIndex) =>
    topicSets.map(([title, meaning], topicIndex) => ({
      ...domain,
      title,
      meaning,
      level: levels[topicIndex],
      category: `${title} في ${domain.section}`,
      reference: domain.references[(domainIndex + topicIndex) % domain.references.length],
    })),
  );
}

function makeQuizItems({ start }) {
  const suffix =
    " وهذا تلخيص منهجي يقصد تقريب فقه السيرة للمتعلم، مع ترك الجزم بما لم يثبت وترك تنزيل الأحكام الخاصة لأهل العلم.";
  const explanation =
    "منهج مجالس العلم في السيرة: تقديم الثابت، وذكر المشهور بتحفّظ، وتجنّب الإسرائيليات والجزم بتاريخٍ مختلف فيه بلا دليل تعبّدي.";
  return roundTopics().map((topic, index) => ({
    id: String(start + index),
    section: topic.section,
    category: topic.category,
    level: topic.level,
    question: `أي عبارة تلخّص منهج ${topic.title} عند دراسة ${topic.section}؟`,
    answer: `${topic.meaning}، مع ملاحظة أن سيرة النبي ﷺ تُقرأ للتأسّي والعمل لا للتفاخر بالمعلومة.${suffix}`,
    explanation,
    reference: topic.reference,
  }));
}

function makeQaItems({ start }) {
  const suffix =
    " وهذا تأصيل مختصر للمذاكرة والعمل، ولا يحوّل القارئ إلى مفتٍ على الوقائع الخاصة بلا بيّنة ولا سؤال للراسخين.";
  return roundTopics()
    .slice(0, 40)
    .map((topic, index) => {
      const [category_id, cat_name, cat_slug] = topic.qa;
      return {
        id: String(start + index),
        question: `ما الضابط العملي لـ${topic.title} في باب ${topic.section}؟`,
        answer: `ضابطه أن يتعامل المسلم مع السيرة بعلم وأدب: فيعمل بأن ${topic.meaning}. ويزن الخبر بالدليل والمصدر، فلا يغلو في العاطفة ولا يجزم بما لم يثبت.${suffix}`,
        category_id,
        ruling_type:
          index % 3 === 0 ? "منهج علمي معتبر" : index % 3 === 1 ? "أدب في الرواية" : "أصل تربوي معتبر",
        reference: topic.reference,
        cat_name,
        cat_slug,
      };
    });
}

function makeFawaidItems() {
  const suffix =
    " وهذه فائدة تعليمية تصلح للتذكير والمنهج، ولا تُنزل على الأعيان إلا بعلم وعدل.";
  return roundTopics()
    .slice(0, 25)
    .map((topic, index) => ({
      text: `من فقه ${topic.title} في ${topic.section} أن ${topic.meaning}، وأن محبة النبي ﷺ تظهر في التأسّي العملي والتثبّت في الرواية وترك الاحتفال بما لم يُشرع.${suffix}`,
      category: index % 5 === 0 ? "السيرة" : topic.fawaidCategory,
      source: topic.reference,
      author_name: index % 2 === 0 ? "أهل العلم" : "محررو مجالس العلم",
    }));
}

