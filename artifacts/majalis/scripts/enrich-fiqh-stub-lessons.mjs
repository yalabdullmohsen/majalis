function isStub(lesson) {
  const title = lesson.title || "";
  const summary = lesson.summary || "";
  const evidence = lesson.evidence || "";
  return (
    /^مدخل إلى/.test(title) ||
    /يتناول هذا المبحث/.test(summary) ||
    /الأصل في مسائل/.test(evidence)
  );
}

function sourcesFor(bookTitle, chapterTitle) {
  const ref = `${bookTitle}، ${chapterTitle}`;
  return [
    { ...AUTHORS.mughni, ref },
    { ...AUTHORS.mumti, ref },
    { ...AUTHORS.mulakhkhas, ref },
  ];
}

function assertQuality(key, body) {
  if (!body.title || /^مدخل إلى/.test(body.title)) {
    throw new Error(`${key}: عنوان غير صالح`);
  }
  if ((body.summary || "").length < 120) throw new Error(`${key}: summary < 120`);
  if ((body.evidence || "").length < 40) throw new Error(`${key}: evidence < 40`);
  if (!(body.preferred || "").trim()) throw new Error(`${key}: preferred فارغ`);
  if (!(body.madhhabNotes || "").trim()) throw new Error(`${key}: madhhabNotes فارغ`);
}

const data = JSON.parse(readFileSync(booksPath, "utf8"));
let updated = 0;
const missing = [];
const reviewDone = [];

for (const book of data.books) {
  for (const chapter of book.chapters) {
    for (const lesson of chapter.lessons || []) {
      if (!isStub(lesson)) continue;
      const key = `${book.id}/${chapter.id}`;
      const body = CONTENT[key];
      if (!body) {
        missing.push(key);
        continue;
      }
      assertQuality(key, body);
      lesson.title = body.title;
      lesson.summary = body.summary;
      lesson.evidence = body.evidence;
      lesson.preferred = body.preferred;
      lesson.madhhabNotes = body.madhhabNotes;
      lesson.sources = sourcesFor(book.title, chapter.title);
      lesson.status = "published";
      updated += 1;
      reviewDone.push(`- [x] ${book.title} / ${chapter.title} — أُثري محتوى stub (مراجعة تخريج بشرية اختيارية)`);
    }
  }
}

if (missing.length) {
  console.error("مفاتيح بلا محتوى:", missing.join(", "));
  process.exit(1);
}

