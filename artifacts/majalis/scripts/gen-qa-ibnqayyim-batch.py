def _vhc():
    spec = importlib.util.spec_from_file_location(
        "vhc", os.path.join(HERE, "verify-hadith-citations.py"))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


QUOTE = re.compile("«(.+?)»", re.S)
AYAH = re.compile("﴿(.+?)﴾", re.S)


def _surah(num: int):
    with open(os.path.join(QURAN, "surah-%03d.json" % num), encoding="utf-8") as fh:
        return json.load(fh)["ayahs"]


def verify() -> int:
    """بوابتان: ﴿﴾ تُقابَل بمصحف المشروع، و«» تُقابَل بصفحات الشاملة."""
    vhc = _vhc()
    cache, total, bad = {}, 0, 0
    qcache, qtotal, qbad = {}, 0, 0
    for full_id, _ref, pages, ayat, evidence, answer in ROWS:
        key = full_id[:8]
        haystacks = []
        for bk, pg in pages:
            ck = (bk, pg)
            if ck not in cache:
                cache[ck] = vhc.normalize(vhc.strip_marks(
                    vhc.page_text(vhc.BOOKS[bk]["id"], pg)))
            haystacks.append(cache[ck])
        qhay = []
        for sura, num in ayat:
            ck = (sura, num)
            if ck not in qcache:
                txt = next(a["text"] for a in _surah(sura)
                           if a["numberInSurah"] == num)
                qcache[ck] = vhc.normalize(vhc.strip_marks(txt))
            qhay.append(qcache[ck])
        for field, text in (("evidence", evidence), ("answer", answer)):
            for m in AYAH.finditer(text):
                a = vhc.normalize(vhc.strip_marks(m.group(1)))
                qtotal += 1
                if not any(a in h for h in qhay):
                    qbad += 1
                    print("✗ مصحف %s/%s: %s" % (key, field, m.group(1)[:90]))
            for m in QUOTE.finditer(text):
                q = m.group(1)
                total += 1
                parts = [p for p in re.split(r"\.\.\.|…", q) if p.strip()]
                ok = False
                for hay in haystacks:
                    pos, good = 0, True
                    for p in parts:
                        np = vhc.normalize(vhc.strip_marks(p))
                        if not np:
                            continue
                        idx = hay.find(np, pos)
                        if idx < 0:
                            good = False
                            break
                        pos = idx + len(np)
                    if good:
                        ok = True
                        break
                if not ok:
                    bad += 1
                    print("✗ الشاملة %s/%s: %s" % (key, field, q[:110]))
    print("مقابلةُ الشاملة: %d/%d مطابقًا حرفيًّا%s"
          % (total - bad, total, "" if not bad else "  ⚠️ %d إخفاقًا" % bad))
    print("مقابلةُ المصحف: %d/%d مطابقًا حرفيًّا%s"
          % (qtotal - qbad, qtotal, "" if not qbad else "  ⚠️ %d إخفاقًا" % qbad))
    return 1 if (bad or qbad) else 0


def q(s: str) -> str:
    return "'" + s.replace("'", "''") + "'"


def main() -> int:
    if "--verify" in sys.argv:
        return verify()
    live = {r["id"][:8]: r for r in json.load(open(sys.argv[1], encoding="utf-8"))["rows"]}
    out = ["-- عنقودُ ابن القيم في qa_questions (أربعةُ صفوف): إسنادُ كلِّ صفٍّ إلى",
           "-- موضعه المطبوع من كتاب ابن القيم المسمَّى في reference نفسِه، بعد أن",
           "-- كان الكتابُ اسمًا في reference لا مستنَدًا في evidence — ج-٢٥٥.",
           "-- مُولَّد آليًّا بـscripts/gen-qa-ibnqayyim-batch.py — لا يُحرَّر يدويًّا.",
           "-- كلُّ UPDATE مقيَّد بالنصوص الأصلية ⇒ idempotent.", ""]
    for full_id, ref, _pages, _ayat, evidence, answer in ROWS:
        key = full_id[:8]
        row = live[key]
        assert row["id"] == full_id, "معرِّف غير مطابق: %s (الفعلي %s)" % (key, row["id"])
        keywords = row["reference"].split(" | ", 1)[1] if " | " in row["reference"] else ""
        new_ref = ref + (" | " + keywords if keywords else "")
        sets = ["answer = %s" % q(answer),
                "reference = %s" % q(new_ref),
                "evidence = %s" % q(evidence),
                "verification_status = 'verified'"]
        where = ["id = %s" % q(row["id"]),
                 "reference = %s" % q(row["reference"]),
                 "evidence = %s" % q(row["evidence"]),
                 "answer = %s" % q(row["answer"])]
        out.append("-- %s | %s" % (key, row["question"]))
        out.append("UPDATE qa_questions SET\n  " + ",\n  ".join(sets)
                   + "\nWHERE " + "\n  AND ".join(where) + ";")
        out.append("")
    with open(os.path.normpath(OUT), "w", encoding="utf-8") as fh:
        fh.write("\n".join(out))
    print("كُتب %d تحديثًا في %s" % (len(ROWS), os.path.normpath(OUT)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
