def q(s: str) -> str:
    return "'" + s.replace("'", "''") + "'"


def main() -> int:
    live = {r["id"][:8]: r for r in json.load(open(sys.argv[1], encoding="utf-8"))}
    out = ["-- دفعة تحقيق صفوف «كتب الفقه الإسلامي» في qa_questions من المغني لابن قدامة",
           "-- (ج-٢٣٨) مُولَّد آليًّا بـscripts/gen-qa-fiqh-mughni-batch.py — لا يُحرَّر يدويًّا.",
           "-- كلُّ UPDATE مقيَّد بالنصوص الأصلية ⇒ idempotent.", ""]
    for full_id, loc, evidence, answer in ROWS:
        key = full_id[:8]
        row = live[key]
        keywords = row["reference"].split(" | ", 1)[1] if " | " in row["reference"] else ""
        new_ref = "%s: %s%s" % (BOOK, loc, (" | " + keywords) if keywords else "")
        sets = ["reference = %s" % q(new_ref),
                "evidence = %s" % q(evidence),
                "verification_status = 'verified'"]
        where = ["id = %s" % q(row["id"]),
                 "reference = %s" % q(row["reference"]),
                 "evidence = %s" % q(row["evidence"])]
        if answer is not None:
            sets.insert(0, "answer = %s" % q(answer))
            where.append("answer = %s" % q(row["answer"]))
        out.append("-- %s | %s" % (key, row["question"]))
        out.append("UPDATE qa_questions SET\n  " + ",\n  ".join(sets)
                   + "\nWHERE " + "\n  AND ".join(where) + ";")
        out.append("")
    with open(os.path.normpath(OUT), "w", encoding="utf-8") as fh:
        fh.write("\n".join(out))
    print("كُتب %d تحديثًا في %s" % (len(ROWS), os.path.normpath(OUT)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
