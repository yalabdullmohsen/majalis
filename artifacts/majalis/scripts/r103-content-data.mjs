function roundTopics() {
  return domains.flatMap((domain, domainIndex) =>
    topicSets.map(([title, meaning], topicIndex) => ({
      ...domain,
      category: `${title} في ${domain.section}`,
      level: levels[topicIndex],
      title,
      meaning,
      reference: domain.references[(domainIndex + topicIndex) % domain.references.length],
    })),
  );
}

function makeQuizItems({ start }) {
  const suffix =
    " وهذا عرض تعليمي يربط الأصل بدليله ومقصده، ولا يغني عن سؤال أهل العلم عند الوقائع الخاصة أو تعارض المصالح.";
  const explanation =
    "تمام الفقه أن يعرف الطالب أصل المسألة وحدودها، ثم ينزلها برفق وعدل وبصيرة، فيحفظ حق الله وحقوق عباده.";
  return roundTopics().map((topic, index) => ({
    id: String(start + index),
    section: topic.section,
    category: topic.category,
    level: topic.level,
    question: `ما المعنى العملي لأصل ${topic.title} عند دراسة باب ${topic.section}؟`,
    answer: `${topic.meaning}، مع فهم النصوص وكلام أهل العلم ومراعاة القدرة والمآلات.${suffix}`,
    explanation,
    reference: topic.reference,
  }));
}

