def q(s: str) -> str:
    return "'" + s.replace("'", "''") + "'"


def main() -> int:
    raw = open(sys.argv[1], encoding="utf-8").read()
    rows = json.loads(raw[raw.index("{"):])["rows"]
    seen = set()
    out = ["BEGIN;"]
    for i, row in enumerate(rows, 1):
        ch = CHANGES.get(row["id"])
        if ch is None:
            print("⚠️ صفٌّ حيٌّ بلا تغيير مخطَّط: %s" % row["id"], file=sys.stderr)
            continue
        seen.add(row["id"])
        sets = []
        if "answer" in ch:
            sets.append("answer=%s" % q(ch["answer"]))
        sets += [
            "evidence=%s" % q(ch["evidence"]),
            "reference=%s" % q(ch["reference"]),
            "source_url=%s" % q(URL % ch["url"]),
            "verification_status='verified'",
            "updated_at=now()",
        ]
        wheres = [
            "id=%s" % q(row["id"]),
            "reference=%s" % q(row["reference"]),
            "evidence=%s" % q(row["evidence"]),
        ]
        if "answer" in ch:
            wheres.append("answer=%s" % q(row["answer"]))
        out.append("-- %d) %s" % (i, row["question"]))
        out.append("UPDATE qa_questions SET " + ",\n       ".join(sets))
        out.append(" WHERE " + "\n   AND ".join(wheres) + ";")
    out.append("COMMIT;")
    missing = set(CHANGES) - seen
    if missing:
        print("⚠️ معرِّفات مخطَّطة لم تُقابَل في الصفوف الحيّة: %s" % ", ".join(missing),
              file=sys.stderr)
        return 1
    print("\n".join(out))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
