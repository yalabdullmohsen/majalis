# عبارات تأجيل/حشو ممنوعة (مطابقة دقيقة للجملة لا لجزء كلمة فقهية مثل «مؤجّلة» أو «تقريبًا»)
FORBIDDEN_RE = [
    r"pending_review",
    r"(?<!\w)مؤجل(?!\w)",
    r"قيد الإضافة",
    r"(?<!\w)قريبًا(?!\w)",
    r"سيتم لاحقًا",
    r"(?<!\w)فارغ(?!\w)",
    r"مدخل إلى",
    r"يتناول هذا المبحث",
    r"الأصل في مسائل",
]


def build_catalog() -> dict[str, Any]:
    books = []
    for b in BOOKS_RAW:
        chapters = []
        for i, (cid, ctitle, core) in enumerate(b["chapters"], start=1):
            chapters.append(expand_chapter(b["id"], b["title"], cid, ctitle, i, core))
        books.append({
            "id": b["id"],
            "title": b["title"],
            "description": b["description"],
            "category": b["category"],
            "order": b["order"],
            "aliases": b["aliases"],
            "chapters": chapters,
        })
    return {
        "version": 2,
        "generatedAt": GENERATED_AT,
        "madhhab": "hanbali",
        "books": books,
    }


def validate(catalog: dict[str, Any]) -> None:
    errors = []
    books = catalog["books"]
    if len(books) != 17:
        errors.append(f"expected 17 books, got {len(books)}")
    for b in books:
        seen = set()
        for ch in b["chapters"]:
            if ch["id"] in seen:
                errors.append(f"duplicate chapter id {b['id']}/{ch['id']}")
            seen.add(ch["id"])
            if ch.get("status") != "published":
                errors.append(f"chapter status {b['id']}/{ch['id']}")
            for field in ("definition", "summary", "evidence"):
                val = (ch.get(field) or "").strip()
                if len(val) < 40:
                    errors.append(f"short {field} {b['id']}/{ch['id']}")
                for bad in FORBIDDEN_RE:
                    if re.search(bad, val):
                        errors.append(f"forbidden '{bad}' in chapter {field} {b['id']}/{ch['id']}")
            if len(ch.get("sources") or []) < 2:
                errors.append(f"sources <2 {b['id']}/{ch['id']}")
            if not ch.get("lessons"):
                errors.append(f"no lessons {b['id']}/{ch['id']}")
            for les in ch["lessons"]:
                if les.get("status") != "published":
                    errors.append(f"lesson status {les['id']}")
                for field in ("summary", "evidence", "preferred", "madhhabNotes"):
                    val = (les.get(field) or "").strip()
                    if not val:
                        errors.append(f"empty lesson {field} {les['id']}")
                    blob = val + "\n" + (les.get("title") or "")
                    for bad in FORBIDDEN_RE:
                        if re.search(bad, blob):
                            errors.append(f"forbidden '{bad}' in lesson {les['id']}")
                if len((les.get("summary") or "").strip()) < 80:
                    errors.append(f"lesson summary <80 {les['id']}")
                if len((les.get("evidence") or "").strip()) < 40:
                    errors.append(f"lesson evidence <40 {les['id']}")
                if len(les.get("sources") or []) < 2:
                    errors.append(f"lesson sources <2 {les['id']}")
    # alias targets exist
    book_ids = {b["id"] for b in books}
    ch_map = {(b["id"], ch["id"]) for b in books for ch in b["chapters"]}
    for a in ALIASES:
        if a["targetBookId"] not in book_ids:
            errors.append(f"alias book missing {a['aliasId']}")
        if (a["targetBookId"], a["targetChapterId"]) not in ch_map:
            errors.append(f"alias chapter missing {a['aliasId']} -> {a['targetBookId']}/{a['targetChapterId']}")
    if errors:
        print("VALIDATION ERRORS:", len(errors), file=sys.stderr)
        for e in errors[:40]:
            print(" -", e, file=sys.stderr)
        if len(errors) > 40:
            print(f" ... and {len(errors)-40} more", file=sys.stderr)
        raise SystemExit(1)


def main() -> None:
    catalog = build_catalog()
    validate(catalog)

    OUT_BOOKS.parent.mkdir(parents=True, exist_ok=True)
    OUT_BOOKS.write_text(json.dumps(catalog, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    OUT_ALIASES.write_text(
        json.dumps({"aliases": ALIASES}, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )

    n_books = len(catalog["books"])
    n_ch = sum(len(b["chapters"]) for b in catalog["books"])
    n_les = sum(len(ch["lessons"]) for b in catalog["books"] for ch in b["chapters"])
    print(f"Wrote {OUT_BOOKS}")
    print(f"Wrote {OUT_ALIASES}")
    print(f"books={n_books} chapters={n_ch} lessons={n_les} aliases={len(ALIASES)}")
    print("all chapter/lesson status=published; summaries non-empty; validated OK")


if __name__ == "__main__":
    main()
