def book_desc(title, theme):
    return (
        f"{title} في المذهب الحنبلي على طريقة الزاد والروض وكشاف القناع، "
        f"ويجمع أبواب {theme} بتحرير معتمد مع أدلته من الكتاب والسنة."
    )


