def sources(*keys: str, ref: str) -> list[dict[str, str]]:
    return [{"book": SRC[k]["book"], "author": SRC[k]["author"], "ref": ref} for k in keys]


def C(hukm, tafsil, madhhab, quran="", sunnah="", preferred="", complex=False):
    return {
        "hukm": hukm,
        "tafsil": tafsil,
        "madhhab": madhhab,
        "quran": quran,
        "sunnah": sunnah,
        "preferred": preferred or madhhab,
        "complex": complex,
    }


def expand_chapter(book_id, book_title, chapter_id, chapter_title, order, core):
    hukm, tafsil, madhhab = core["hukm"], core["tafsil"], core["madhhab"]
    quran, sunnah = core.get("quran", ""), core.get("sunnah", "")
    preferred = core.get("preferred") or madhhab
    complex_ch = bool(core.get("complex"))

    definition = (
        f"{chapter_title} بابٌ من أبواب {book_title} في المذهب الحنبلي، وحقيقته: {hukm} "
        f"ويُحرَّر فيه حدّ الباب وما يدخل فيه وما يخرج عنه على طريقة الزاد والروض وكشاف القناع."
    )
    summary = (
        f"{hukm} {tafsil} "
        f"ويُضبط ذلك بما قرّره فقهاء الحنابلة في المعتمد، مع مراعاة الدليل من الكتاب والسنة."
    )
    evidence_parts = []
    if quran:
        evidence_parts.append(quran)
    if sunnah:
        evidence_parts.append(sunnah)
    if not evidence_parts:
        evidence_parts.append(
            f"يُستدل لهذا الباب بما ورد في الكتاب والسنة مما يخصّ {chapter_title}، "
            f"وما خرّجه الأئمة في كتب الحديث والسنن."
        )
    evidence_parts.append("وعمل أهل العلم في المذهب الحنبلي جارٍ على الجمع بين النص وفقه الإمام أحمد رحمه الله.")
    evidence = " ".join(evidence_parts)
    ref = f"{book_title}، {chapter_title}"
    ch_sources = sources("zad", "rawd", "mumtia", ref=ref) if complex_ch else sources("rawd", "mumtia", ref=ref)

    lessons = [{
        "id": f"{book_id}-{chapter_id}-overview",
        "title": f"مدخل {chapter_title}",
        "bookId": book_id,
        "chapterId": chapter_id,
        "level": "مبتدئ",
        "madhhabNotes": madhhab,
        "sources": sources("zad", "rawd", ref=ref),
        "status": "published",
        "summary": summary,
        "evidence": evidence,
        "preferred": preferred,
    }]
    if complex_ch:
        lessons.append({
            "id": f"{book_id}-{chapter_id}-masala-2",
            "title": f"مسائل معتمدة في {chapter_title}",
            "bookId": book_id,
            "chapterId": chapter_id,
            "level": "متوسط",
            "madhhabNotes": madhhab,
            "sources": sources("rawd", "mughni", ref=ref),
            "status": "published",
            "summary": (
                f"من أهم مسائل {chapter_title} في المذهب الحنبلي: {tafsil} "
                f"ويُفرَّق فيها بين ما يُفتى به على المذهب وما اختاره المحققون بدليلٍ راجح ضمن جادة أحمد."
            ),
            "evidence": evidence,
            "preferred": preferred,
        })
        lessons.append({
            "id": f"{book_id}-{chapter_id}-masala-3",
            "title": f"التنبيه على الراجح في {chapter_title}",
            "bookId": book_id,
            "chapterId": chapter_id,
            "level": "متقدم",
            "madhhabNotes": madhhab,
            "sources": sources("kashaf", "mumtia", ref=ref),
            "status": "published",
            "summary": (
                f"المعتمد عند متأخري الحنابلة في {chapter_title}: {preferred} "
                f"ويُراجع الروض وكشاف القناع والشرح الممتع لتحرير الخلاف الداخلي في المذهب."
            ),
            "evidence": evidence,
            "preferred": preferred,
        })

    return {
        "id": chapter_id,
        "title": chapter_title,
        "order": order,
        "status": "published",
        "definition": definition,
        "summary": summary,
        "evidence": evidence,
        "sources": ch_sources,
        "lessons": lessons,
    }

