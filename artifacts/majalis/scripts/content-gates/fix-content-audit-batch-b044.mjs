function expandFaqBody(it, a) {
  const title = it.title || "";
  const answerMatch = String(it.body || "").match(/## الجواب\n([\s\S]*?)(?:\n\n##|$)/);
  const answer = (answerMatch ? answerMatch[1] : "").trim() || "راجع الجواب المختصر أعلاه.";
  return [
    `## السؤال`,
    title,
    ``,
    `## الجواب`,
    answer,
    ``,
    `## دليل قرآني مرتبط`,
    `﴿${a.text}﴾ — ${a.ref.replace(":", ":")}`,
    ``,
    `## توجيه`,
    `الجواب للمتعلم وحديث العهد مختصر وهادئ. إن احتجت تفصيلًا فقهيًا فاسأل عالمًا موثوقًا، ولا تجعل تعليقات الإنترنت مرجعًا وحيدًا.`,
  ].join("\n");
}

function fixIntro() {
  const fp = path.join(KNOWLEDGE, "intro-islam", "topics.json");
  const data = JSON.parse(fs.readFileSync(fp, "utf8"));
  let n = 0;
  for (const it of data.items || []) {
    const spec = INTRO_BODIES[it.id];
    if (!spec) continue;
    const [s, a] = spec.ayah;
    const ev = ayah(s, a);
    it.title = spec.title;
    it.body = spec.body.trim();
    it.evidences = [ev];
    it.sources = [
      mushafSrc(`${s}:${a}`),
      { book: "تيسير الكريم الرحمن", author: "السعدي", locator: "المعنى الإجمالي" },
    ];
    it.updated_at = TODAY;
    it.review_status = "verified";
    n++;
    if ((it.body.match(/## تفصيل موجز/g) || []).length > 0) {
      throw new Error(`${it.id} still has boilerplate`);
    }
    if ((it.body.match(/## تحذير/g) || []).length > 1) {
      throw new Error(`${it.id} still has duplicated warnings`);
    }
  }
  fs.writeFileSync(fp, JSON.stringify(data, null, 2) + "\n");
  console.log(`intro-islam: rewritten ${n} topics`);
}

function fixHistory() {
  const fp = path.join(KNOWLEDGE, "history", "timeline.json");
  const data = JSON.parse(fs.readFileSync(fp, "utf8"));
  let n = 0;
  for (const it of data.items || []) {
    const ref = HISTORY_AYAH[it.id];
    if (!ref) continue;
    const [s, a] = ref;
    it.evidences = [ayah(s, a)];
    // وسّع قليلًا إن كان المتن قصيرًا جدًا دون حشو مكرر
    const wc = wordCount(it.body);
    if (wc < 180 && !String(it.body).includes("## عبرة")) {
      it.body = `${it.body.trim()}\n\n## عبرة\nيُقرأ التاريخ للعبرة وحفظ الدين ونصرته، لا للطعن في الصحابة ولا لتقديس الملوك بلا دليل. والعمدة ما صحّ من النقل مع الإنصاف.`;
    }
    // أزل اعتماد مصادر غير مناسبة إن وُجدت كمصدر أوحد للمرحلة
    it.sources = [
      ...(it.sources || []).filter((s) => s.book !== "الرحيق المختوم" || /سيرة|بعث|هجرة|المدينة|جاهلية/.test(it.id)),
      mushafSrc(`${s}:${a}`),
    ];
    // unique sources by book
    const seen = new Set();
    it.sources = it.sources.filter((s) => {
      const k = s.book + "|" + (s.locator || "");
      if (seen.has(k)) return false;
      seen.add(k);
      return true;
    });
    it.updated_at = TODAY;
    n++;
  }
  fs.writeFileSync(fp, JSON.stringify(data, null, 2) + "\n");
  console.log(`history: fixed ayah affinity for ${n} items`);
}

function fixFaqs() {
  const fp = path.join(KNOWLEDGE, "discover-islam", "path-and-faq.json");
  const data = JSON.parse(fs.readFileSync(fp, "utf8"));
  let n = 0;
  for (const it of data.items || []) {
    if (!String(it.id || "").startsWith("discover-faq-")) continue;
    const [s, aNum] = faqAyahFor(it.title);
    const ev = ayah(s, aNum);
    it.evidences = [ev];
    it.body = expandFaqBody(it, ev);
    it.sources = [mushafSrc(`${s}:${aNum}`)];
    it.updated_at = TODAY;
    n++;
  }
  fs.writeFileSync(fp, JSON.stringify(data, null, 2) + "\n");
  console.log(`discover-faq: retargeted ayahs for ${n} items`);
}

