function ayah(s, a) {
  const ay = getAyah(s, a);
  if (!ay) throw new Error(`missing ayah ${s}:${a}`);
  return { type: "ayah", ref: `${s}:${a}`, text: ay.text, grade: "", graded_by: "" };
}

