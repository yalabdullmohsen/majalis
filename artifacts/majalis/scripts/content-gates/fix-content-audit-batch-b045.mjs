/** توسيع إجابة FAQ حسب موضوع العنوان — جمل مفيدة لا حشو. */
function faqExtra(title, answer) {
  const t = title || "";
  if (/صلاة|نصل/.test(t))
    return "الصلوات الخمس مفروضة في اليوم والليلة، وتُقضى إن فاتت بعذر على تفصيل أهل العلم. تعلّم شروطها وأركانها من مصدر ميسر قبل الإكثار من النوافل.";
  if (/زكاة|صدق/.test(t))
    return "الزكاة ركن على من ملك النصاب وحال عليه الحول بشروطه؛ والصدقة أوسع بابًا. لا تؤخر زكاة مالك إن وجبت.";
  if (/صوم|رمضان/.test(t))
    return "صوم رمضان واجب على المسلم البالغ القادر؛ والمريض والمسافر لهما رخص معلومة. اسأل عن حالتك الخاصة عالمًا.";
  if (/حج|عمر/.test(t))
    return "الحج مرة في العمر على المستطيع؛ والعمرة سنة مؤكدة عند الجمهور. لا تؤخر الحج مع القدرة بلا عذر.";
  if (/ولد|شريك/.test(t))
    return "الله أحد صمد لم يلد ولم يولد؛ ونسبة الولد إليه شرك يناقض التوحيد.";
  if (/قرآن/.test(t))
    return "القرآن كلام الله المحفوظ؛ يُقرأ ويُعمل به، ويُرجع في معناه للتفسير المعتبر لا للآراء العابرة.";
  if (/محمد|نبي|رسول/.test(t))
    return "محمد ﷺ خاتم النبيين، بشر رسول يُتبع ولا يُعبد. محبته باتباع سنته لا بالغلو.";
  if (/حسد|عين/.test(t))
    return "الحسد مذموم، والعين حق كما في السنة الصحيحة؛ والعلاج الشرعي الرقية والأذكار لا الشعوذة.";
  if (/غضب/.test(t))
    return "الغضب جمرة؛ والعلاج الاستعاذة والوضوء والسكوت وتغيير الهيئة كما في السنة.";
  if (/مهدي|دجال|ساعة/.test(t))
    return "يُقتصر على ما صح في الأخبار؛ ويُترك التفصيل الواهي. الإيمان باليوم الآخر والعمل الصالح أولى من تتبع الروايات الضعيفة.";
  if (/أعظم آية|أعظم سورة/.test(t))
    return "ثبت فضل آية الكرسي وفضل سورة الإخلاص وغيرها في الصحيح؛ من دون تفضيل يُلغي العمل ببقية القرآن.";
  if (/توبة|استغفار/.test(t))
    return "التوبة النصوح: إقلاع وندم وعزم، وردّ المظالم إن تعلقت بحقوق العباد.";
  if (/شرك/.test(t))
    return "الشرك أكبر الكبائر؛ منه صرف العبادة لغير الله. والتوبة منه مقبولة قبل الغرغرة لمن صدق.";
  if (/ربا|بنك/.test(t))
    return "الربا محرم قطعًا؛ والتعاملات المعاصرة تُعرض على أهل الفقه ولا تُبرَّر بالعادة وحدها.";
  if (/علم|فتوى|شبهة|مصدر/.test(t))
    return "خذ العلم عن الثقات، واطلب الدليل، وحاذر الفتاوى المجهولة على الإنترنت.";
  // fallback short enrichment of existing answer
  if (answer && answer.length > 8) {
    return "اعمل بما علمت في حدود استطاعتك، واسأل أهل العلم عند الإشكال الخاص.";
  }
  return "الجواب مختصر للمتعلم؛ والتفاصيل عند أهل العلم الموثوقين.";
}

function fixDoubts() {
  const fp = path.join(KNOWLEDGE, "discover-islam", "path-and-faq.json");
  const data = JSON.parse(fs.readFileSync(fp, "utf8"));
  let n = 0;
  for (const it of data.items || []) {
    const spec = DOUBTS[it.id];
    if (!spec) continue;
    const [s, a] = spec.ayah;
    const ev = ayah(s, a);
    // embed exact ayah snippet if quoted loosely
    it.title = spec.title;
    it.body = spec.body.trim();
    // ensure 2:256 exact if mentioned - doubt-002 mentions concept
    if (it.id === "discover-doubt-002") {
      const a256 = getAyah(2, 256);
      it.body = it.body.replace(
        /﴿لَا إِكْرَاهَ فِي الدِّينِ﴾/,
        `﴿${a256.text}﴾`,
      );
      it.evidences = [ev, ayah(2, 256)];
    } else {
      it.evidences = [ev];
    }
    it.sources = [mushaf(s, a)];
    it.updated_at = TODAY;
    it.review_status = "verified";
    n++;
    if (wordCount(it.body) < 60) throw new Error(`${it.id} still thin ${wordCount(it.body)}`);
    if (/للتوسع راجع التعريف/.test(it.body)) throw new Error(`${it.id} still boilerplate`);
  }
  fs.writeFileSync(fp, JSON.stringify(data, null, 2) + "\n");
  console.log(`doubts expanded: ${n}`);
}

function expandFaqs() {
  const fp = path.join(KNOWLEDGE, "discover-islam", "path-and-faq.json");
  const data = JSON.parse(fs.readFileSync(fp, "utf8"));
  let n = 0;
  for (const it of data.items || []) {
    if (!String(it.id || "").startsWith("discover-faq-")) continue;
    if (wordCount(it.body || "") >= 75) continue;
    const answerMatch = String(it.body || "").match(/## الجواب\n([\s\S]*?)(?:\n\n##|$)/);
    const answer = (answerMatch ? answerMatch[1] : "").trim();
    const ev = (it.evidences || [])[0];
    if (!ev?.text || !ev?.ref) continue;
    const [s, a] = String(ev.ref).split(":").map(Number);
    const extra = faqExtra(it.title, answer);
    it.body = [
      "## السؤال",
      it.title,
      "",
      "## الجواب",
      answer || "راجع أهل العلم في تفصيل المسألة.",
      "",
      "## بيان أوضح",
      extra,
      "",
      "## دليل مرتبط",
      `﴿${ev.text}﴾ (${ev.ref})`,
      "",
      "## توجيه",
      "هذا للمتعلم وحديث العهد. النوازل الشخصية تُسأل فيها عالمًا موثوقًا.",
    ].join("\n");
    it.updated_at = TODAY;
    n++;
  }
  fs.writeFileSync(fp, JSON.stringify(data, null, 2) + "\n");
  console.log(`faqs enriched: ${n}`);
}

fixDoubts();
expandFaqs();
