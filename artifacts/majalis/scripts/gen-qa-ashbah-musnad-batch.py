# ── قراءة الصفوف الحيّة ثم بناء SQL مقيَّد بها ───────────────────────────────
def live_rows(ids):
    sql = ("select id, answer, reference, evidence from qa_questions where id in (%s);"
           % ", ".join("'%s'" % i for i in ids))
    path = "/tmp/qa-ashbah-musnad-live.sql"
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(sql)
    out = subprocess.run(["npx", "supabase", "db", "query", "--linked", "-f", path],
                         cwd=ROOT, capture_output=True, text=True).stdout
    data = json.loads(out[out.index("{"):])
    return {r["id"]: r for r in data["rows"]}


def q(s):
    return "'" + s.replace("'", "''") + "'" if s is not None else "NULL"


def main():
    rows = build()
    live = live_rows([r["id"] for r in rows])
    print("-- تدقيق `qa_questions` — صنفا «الأشباه والنظائر للسيوطي» و«مسند أحمد» (ج-٢٣٧)")
    print("-- مولَّد آليًّا بـ scripts/gen-qa-ashbah-musnad-batch.py — لا يُحرَّر باليد.")
    print("-- كل `UPDATE` مقيَّد بالحالة الأصليّة للصفّ ⇒ idempotent، ولا يمسّ صفًّا تغيّر بعدُ.")
    print()
    for r in rows:
        cur = live.get(r["id"])
        if not cur:
            print("-- ⚠️ الصفّ %s غير موجود — تُخُطِّي." % r["id"])
            continue
        print("-- %s" % r["note"])
        sets = ["reference = %s" % q(r["reference"]),
                "evidence = %s" % q(r["evidence"]),
                "verification_status = 'verified'"]
        where = ["id = '%s'" % r["id"],
                 "reference = %s" % q(cur["reference"]),
                 "evidence = %s" % q(cur["evidence"])]
        if r["answer"] is not None:
            sets.insert(0, "answer = %s" % q(r["answer"]))
            where.append("answer = %s" % q(cur["answer"]))
        print("UPDATE qa_questions SET\n  %s\nWHERE %s;" % (",\n  ".join(sets), "\n  AND ".join(where)))
        print()
    return 0


