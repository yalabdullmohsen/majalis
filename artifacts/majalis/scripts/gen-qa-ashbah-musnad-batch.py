# ── قصّ المقتبس بحروفه وتشكيله ──────────────────────────────────────────────
def _raw_end(raw: str, last: int) -> int:
    """نهاية القصّ في النصّ الأصليّ: بعد آخر حرفٍ مطابق **مع تشكيله التابع له**.

    طولُ المقطع المطبَّع ليس طولَه في الأصل (التشكيل يُسقَط في التطبيع)، فلو قُطع
    بطول المطبَّع لسقط آخر الكلمة — وهو خطأ نقلٍ في نصّ منقول حرفًا.
    """
    end = last + 1
    # التشكيل يُسقَط في التطبيع، وكذلك الهمزات المفردة («الرِّيَاءُ» ⇐ «الريا») —
    # فلو وقف القصّ على آخر حرفٍ مطبَّع لسقطت همزةُ آخر الكلمة وتشكيلُها.
    while end < len(raw) and (V.TASHKEEL.match(raw[end]) or raw[end] in "ءؤئ"):
        end += 1
    return end


def _clean(s: str) -> str:
    """إسقاط علامات الطبع لا الحروف: أقواس العناوين المعقوفة وعلامات التنصيص الغربية.

    «[قَاعِدَةٌ: الْأَصْلُ بَرَاءَةُ الذِّمَّةِ]» عنوانٌ معقوف في الطبعة، فيبقى نصُّه ويسقط
    قوسه؛ و`"` في المسند تُحيط بكلام النبي ﷺ داخل الحديث، وتُغني عنها «» في الاقتباس.
    """
    return re.sub(r"\s+", " ", s.replace('"', " ").replace("[", " ").replace("]", " ")).strip(" ،.")



def literal_span(book: str, page: int, start: str, end: str) -> str:
    """أقصر مقطع من نصّ الصفحة يبدأ بـ`start` وينتهي بـ`end` — **بتشكيله كما طُبع**.

    المطابقة بالتطبيع (فالطالب يكتب بلا تشكيل)، والقصّ من النصّ الأصليّ عبر خريطة
    فهارس تربط كل حرف مطبَّع بموضعه الأصليّ.
    """
    raw = V.page_text(V.BOOKS[book]["id"], page)
    norm, idx = [], []
    for i, ch in enumerate(raw):
        n = V.normalize(ch)
        if not n:
            if norm and norm[-1] != " " and re.match(r"\s", ch):
                norm.append(" ")
                idx.append(i)
            continue
        norm.append(n)
        idx.append(i)
    ns = "".join(norm)
    a = ns.find(V.normalize(start))
    if a < 0:
        raise SystemExit("لم يوجد أوّل المقتبس في %s/%s: %s" % (book, page, start))
    ne = V.normalize(end)
    b = ns.find(ne, a)
    if b < 0:
        raise SystemExit("لم يوجد آخر المقتبس في %s/%s: %s" % (book, page, end))
    return _clean(raw[idx[a]: _raw_end(raw, idx[b + len(ne) - 1])])


def hadith_span(book: str, page: int, number: int, start: str, end: str) -> str:
    """كسابقتها لكن داخل حديثٍ بعينه من الصفحة — لئلّا يُقتبس من حديثٍ مجاور."""
    for num, text in V.hadiths_on_page(V.BOOKS[book]["id"], page):
        if num != number:
            continue
        norm, idx = [], []
        for i, ch in enumerate(text):
            n = V.normalize(ch)
            if not n:
                if norm and norm[-1] != " " and re.match(r"\s", ch):
                    norm.append(" ")
                    idx.append(i)
                continue
            norm.append(n)
            idx.append(i)
        ns = "".join(norm)
        a = ns.find(V.normalize(start))
        ne = V.normalize(end)
        b = ns.find(ne, a) if a >= 0 else -1
        if a >= 0 and b >= 0:
            return _clean(text[idx[a]: _raw_end(text, idx[b + len(ne) - 1])])
    raise SystemExit("لم يوجد المقتبس في %s ح%s" % (book, number))


def footnote(book: str, page: int, number: int, must_contain: str, upto: str) -> str:
    """حكم المحقِّق من حاشية الصفحة رقمَ `number`، مقطوعًا عند `upto`.

    `must_contain` حارسٌ لازم: ترقيم الحواشي في الصفحة يخصّ **مواضعها من المتن** لا
    أرقام الأحاديث، فلا يُنسب حكمٌ إلى حديثٍ إلا بعد التثبّت من أن الحاشية تتكلّم عليه
    (باسم راوٍ من إسناده مثلًا) — وإلّا نُسب إلى الحديث حكمُ جاره.
    و`upto` تقصر المنقول على **جملة الحكم** دون ما بعدها من التخريج المطوَّل.
    """
    fn = V.page_footnotes(V.BOOKS[book]["id"], page)
    txt = fn.get(number, "")
    if V.normalize(must_contain) not in V.normalize(txt):
        raise SystemExit("حاشية %s/%s (%d) لا تخصّ الموضع المطلوب" % (book, page, number))
    norm, idx = [], []
    for i, ch in enumerate(txt):
        n = V.normalize(ch)
        if not n:
            if norm and norm[-1] != " " and re.match(r"\s", ch):
                norm.append(" ")
                idx.append(i)
            continue
        norm.append(n)
        idx.append(i)
    ns, nu = "".join(norm), V.normalize(upto)
    e = ns.find(nu)
    if e < 0:
        raise SystemExit("لم يوجد آخر الحكم في حاشية %s/%s (%d)" % (book, page, number))
    return _clean(txt[: _raw_end(txt, idx[e + len(nu) - 1])])


