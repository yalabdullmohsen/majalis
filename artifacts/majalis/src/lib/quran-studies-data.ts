/** يقبل عنواناً مجرداً أو زوجاً [عنوان، ملخص تعريفي موجز]. */
function ls(prefix: string, items: (string | [string, string])[]): DarsItem[] {
  return items.map((item, i) => {
    const [title, summary] = Array.isArray(item) ? item : [item, undefined];
    return { id: `${prefix}-${i + 1}`, title, ...(summary ? { summary } : {}) };
  });
}

