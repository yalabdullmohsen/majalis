/**
 * نموذج بيانات «الأمم السابقة» — مصدر مركزي واحد لكل ما يُعرض عن كل قوم:
 * البطاقة، والقصة الكاملة، والقصة المختصرة، وأسئلة المسابقة، وبيانات SEO.
 * لا يُنسخ محتوى هذا النموذج إلى أي قسم آخر؛ كل قسم يقرأ منه مباشرة.
 *
 * الضوابط الشرعية المطبَّقة في البيانات:
 *  • القرآن أولاً، ثم الحديث الصحيح، ثم قول المفسر المعتبر — ولكل درجة وسم
 *    بصري مستقل عبر `EvidenceKind`.
 *  • لا يُثبت نبيٌّ لقومٍ إلا بدليل: `prophetKnown = false` عند عدم الثبوت.
 *  • ما لم يرد فيه نص يُصرَّح به في `notKnown` بدل ملء الفراغ بالتخمين.
 *  • الإسرائيليات لا تُعرض بصيغة الحقائق؛ موضعها `unverified` مع بيان حالها.
 */

/** درجة النص المعروض — تُميَّز بصرياً في الواجهة بلون وأيقونة مستقلين. */
export type EvidenceKind =
  | "quran"       // نص قرآني منقول حرفياً من مصحف المشروع
  | "hadith"      // حديث صحيح بتخريجه
  | "tafsir"      // قول مفسّر معتبر منسوب إليه
  | "disputed"    // مسألة فيها خلاف معتبر بين أهل العلم
  | "unverified"; // رواية غير ثابتة أو إسرائيلية — تُعرض للتحذير لا للاعتماد

export type Evidence = {
  kind: EvidenceKind;
  /** نص الآية أو الحديث أو القول. الآيات منقولة بالرسم الإملائي بين ﴿﴾. */
  text: string;
  /** المرجع: «سورة هود: 25-49» أو «رواه البخاري: 3341». */
  ref: string;
  /** درجة الحديث عند أهل الشأن — للأحاديث فقط. */
  grade?: string;
};

/** أنواع العقوبات الواردة في النصوص — تُستعمل للفلترة والأيقونات. */
export type PunishmentType =
  | "الطوفان"
  | "الريح العقيم"
  | "الصيحة"
  | "الرجفة"
  | "الصاعقة"
  | "الخسف"
  | "قلب القرى"
  | "الحاصب"
  | "الغرق"
  | "الظلة"
  | "المسخ"
  | "طير أبابيل"
  | "تفريق وسيل العرم"
  | "النجاة والإيمان"   // لمن آمن فلم يُعذَّب
  | "غير مفصل"          // عذاب وقع مجملاً دون تعيين نوعه في النص
  | "لم يقع بعد";       // ما أخبر الوحي بوقوعه في المستقبل

/** فصل من فصول القصة الكاملة. */
export type NationChapter = {
  id: string;
  title: string;
  /** فقرات السرد. كل عنصر فقرة مستقلة. */
  body: string[];
  /** الأدلة المرتبطة بهذا الفصل تحديداً، تُعرض في نهايته. */
  evidences?: Evidence[];
  /** تصريح بما لم يرد فيه نص — يُعرض بوسم مستقل. */
  notKnown?: string;
};

export type Nation = {
  slug: string;
  /** الاسم المعتمد للعرض. */
  name: string;
  /** مرادفات للبحث: «عاد» ← «قوم هود»، «الأحقاف». */
  aliases: string[];
  /** النبي المرسل إليهم إن ثبت. */
  prophet?: { name: string; slug?: string };
  /** هل ثبت إرسال نبي بعينه إليهم؟ */
  prophetKnown: boolean;
  /** المكان كما ورد، أو «غير محدد بدقة». */
  place: string;
  /** الحقبة، أو «غير محدد بدقة». */
  era: string;
  /** ترتيب تقريبي للعرض الزمني — تقريبي لا قطعي، وnull لما لا يُعرف موضعه. */
  eraOrder: number | null;
  /** أبرز صفاتهم وأحوالهم. */
  traits: string[];
  /** الذنب أو سبب العقوبة. */
  sin: string;
  /** أسلوب النبي في دعوتهم — فارغ حيث لا نبي معيَّن. */
  dawahMethod?: string;
  /** موقفهم من الدعوة. */
  response: string;
  /** هل آمنوا؟ يُستعمل للفلترة. */
  believed: boolean;
  punishment: {
    type: PunishmentType;
    /** وصف العقوبة كما وردت في النصوص. */
    description: string;
  };
  /** من نجا وسببُ نجاته. */
  survivors: string;
  /** مواضع القصة في القرآن. */
  quranRefs: { surah: string; ayahs: string; note?: string }[];
  /** الأحاديث الصحيحة المتعلقة، إن وُجدت. */
  hadiths: Evidence[];
  /** العبر والفوائد. */
  lessons: string[];
  /** ما ثبت وما لم يثبت وما اختُلف فيه. */
  establishedVsDisputed: { claim: string; status: "ثابت" | "مختلف فيه" | "لم يثبت"; note: string }[];
  /** خلاصة القصة — وضع القراءة المختصر والبطاقة وSEO. */
  summary: string;
  /** فصول القصة الكاملة. */
  chapters: NationChapter[];
  /** «ماذا نتعلم من قصتهم اليوم؟» */
  todayLesson: string[];
  /** أوجه التشابه والاختلاف مع بقية الأمم. */
  comparisons: string[];
  /** وسوم للفلترة: «بنو إسرائيل»، «بلا نبي مسمّى»، «آمنوا»… */
  tags: string[];
  /** موقع تقريبي للخريطة — فقط لما عليه دليل معتبر. */
  approxLocation?: { lat: number; lng: number; label: string };
};
