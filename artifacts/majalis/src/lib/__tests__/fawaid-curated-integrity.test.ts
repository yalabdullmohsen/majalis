  "لا سجلَّ يدسُّ كلمةً بين كلمتَينِ متلاصقتَينِ في الصحيحِ المعزوِّ إليه",
  insertedWord.map((f) => `${f.id}: ${f.text.slice(0, 55)}`).join(" | ")
