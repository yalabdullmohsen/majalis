// ─── ٣٦) لفظٌ ثابتٌ في الصحيحِ المعزوِّ إليه مسبوقٌ بكلماتٍ مقلوبةٍ عنه ───

/**
 * 🔑 **عطبُ ج-٢٩٥ — وموضعُه ما لا تنظرُ إليه البواباتُ كلُّها**: خمسةُ صفوفٍ
 * (`fawaid-curated-118` و-٣٤٨ و-٥٧٠ و-٧٩٢ و-١٠١٤) كانت تسوقُ حديثَ مسلمٍ
 * (٦٥٩٢ بترقيمِ النسخة) هكذا: «**ما نقص مال من صدقة**، وما زاد الله عبدًا
 * بعفو إلا عزًّا، وما تواضع أحد لله إلا رفعه الله» معزوًّا إلى «رواه مسلم» —
 * وعجزُه لفظُ مسلمٍ **بنصِّه**، أمّا صدرُه فلفظُه «**ما نقصت صدقة من مال**»:
 * الكلماتُ هي هي، والترتيبُ مقلوبٌ (الفاعلُ صار مجرورًا والمجرورُ فاعلًا).
 * **والملفُّ نفسُه برهنَ على الصواب**: يكتبُها في ستةِ مواضعَ أُخَرَ («ما
 * نقصت صدقة من مال» في `fawaid-curated-seed:99` و`fawaid-seed` و`quiz-seed`
 * و`prophetic-medicine-seed` و`verified-hadith-fill-sahih`) على لفظِ النسخة.
 *
 * وأفلتت العائلةُ من كلِّ بواباتِ المقابلةِ السابقةِ لأنَّ كلًّا منها تسألُ
 * عن **النافذةِ نفسِها**: أثابتةٌ هي في المعزوِّ إليه (٢٢) أم في الآخرِ (٣٤)
 * أم شطراها في اثنَين (٢٣، ٣٣)؟ — وهذه النافذةُ ثابتةٌ في المعزوِّ إليه
 * بنصِّها فتمرُّ سالمةً، **والعطبُ فيما قبلَها لا فيها**.
 *
 * فالفحصُ يسألُ سؤالًا جديدًا: إذا كانت نافذةُ ثمانِ كلماتٍ **ثابتةً بنصِّها**
 * في الصحيحِ المعزوِّ إليه ⇒ فهي لفظُ روايةٍ قطعًا، فالكلماتُ الخمسُ التي
 * تسبقُها في **الوحدةِ نفسِها** (لا يقطعُها «؛» ولا «:» ولا «»» ولا شرطة)
 * حقُّها أن تكونَ من الروايةِ نفسِها ⇒ فإن لم يوجدْ في تلك النسخةِ حديثٌ
 * واحدٌ تقعُ فيه الكلماتُ السابقةُ ثمَّ النافذةُ متتابعةً (ولو متفرِّقة)
 * فالصدرُ ليس من لفظِ الرواية.
 *
 * ⚠️ **وثلاثةُ قيودٍ لولاها لأسقطَ الفحصُ سليمًا** — كلُّها انكشفت بمراجعةِ
 * كلِّ ساقطٍ فردًا فردًا (١٥ ساقطًا في أوَّلِ صياغة، ١٠ منها إيجابٌ كاذب):
 *   (١) **تسامحُ التتابعِ** (`isSubsequenceOf`) على **كلِّ أحاديثِ النسخة**
 *       لا على ما يحوي النافذةَ بنصِّه وحدَه: فـ«لا تحاسدوا ولا تناجشوا ولا
 *       تباغضوا… وكونوا عباد الله إخوانًا» يحذفُ جملةَ البيعِ من مسلمٍ ٦٥٤١
 *       ⇒ **اختصارٌ عرفُه صحيحٌ في هذا الملفِّ** (٥ صفوفٍ نجت بهذا القيد).
 *   (٢) **تسويةُ واوِ العطفِ وفائِه** في المقابلة: البخاريُّ ٢٤٤٢ «**و**من
 *       كان في حاجة أخيه» والسجلُّ «**من** كان…» — فرقُ حرفٍ عاطفٍ لا قلبَ
 *       لفظٍ (٥ صفوفٍ نجت به).
 *   (٣) **تطبيعٌ أشدُّ للهمزة** (`normStrict`: تُحذفُ الهمزةُ بحاملِها) —
 *       فـ`normHadith` يحذفُ «ء ؤ ئ» ويُبقي حاملَ «أ» ألفًا، فيصيرُ رسمُ
 *       النسخةِ «اقرءوا» ⇐ «اقروا» ورسمُ السجلِّ «اقرأوا» ⇐ «اقراوا»
 *       فيفترقان وهما لفظٌ واحد (مسلم ١٨٧٤، صفٌّ نجا به).
 * وبهذه القيودِ أخرج الفحصُ **٥ صفوفٍ بلا إيجابٍ كاذبٍ واحدٍ** من ٢١٩٠ سجلًّا.
 *
 * ج-٣٠٤ — **وقوبل حدّاه كلاهما فرجعا سليمَين**: النافذةُ ثمانٍ ⇐ ستٌّ (٠ فرقًا)،
 * والصدرُ خمسُ كلماتٍ ⇐ ثلاثٌ (٠ فرقًا) على ٢٨٠٦ سجلًّا — فلا عطبَ تحتَهما.
 */
/** (`normStrict` و`strictWords` و`bareConj` و`isSubsequenceLoose` مرفوعةٌ
 *  إلى ما قبلَ الفحصِ ٣٢ منذ ج-٣٠٣، إذ صار يستعملُها هو أيضًا.) */
const transposedHead = [...FAWAID_CURATED_SEED, ...SEED_FAWAID].filter((f) => {
  const idx = sahihIdxOf(f.author_name);
  if (idx < 0 || REJECTED.test(f.text) || REJECTED.test(f.source ?? "")) return false;
  for (const unit of f.text.split(/[؛:«»—…]/)) {
    const w = normStrict(unit).split(" ").filter(Boolean);
    for (let i = 1; i + 8 <= w.length; i++) {
      const win = w.slice(i, i + 8);
      // نافذةٌ ثابتةٌ بنصِّها في المعزوِّ إليه ⇒ لفظُ روايةٍ قطعًا
      if (!strictCorpus[idx].includes(win.join(" "))) continue;
      const pre = w.slice(Math.max(0, i - 5), i);
      if (!pre.length) continue;
      // …فحقُّ ما قبلَها أن يكونَ من الروايةِ نفسِها، ولو باختصار
      if (strictWords[idx].some((h) => isSubsequenceLoose([...pre, ...win], h))) continue;
      return true;
    }
  }
  return false;
});
assert(
  transposedHead.length === 0,
  "لا سجلَّ يُلصِقُ بلفظٍ ثابتٍ في الصحيحِ المعزوِّ إليه صدرًا مقلوبًا عن لفظِه",
  transposedHead.map((f) => `${f.id}: ${f.text.slice(0, 55)}`).join(" | ")
);

// ─── ٣٧) ذيلٌ ملحَقٌ بلفظٍ مميِّزٍ من الصحيحِ المعزوِّ إليه وليس من روايتِه ───

/**
 * 🔑 **عطبُ ج-٢٩٦ — وموضعُه ما بعدَ اللفظِ لا ما قبلَه**: ثلاثُ عائلاتٍ
 * (١٣ صفًّا) تسوقُ لفظًا **ثابتًا بنصِّه** في الصحيحِ المعزوِّ إليه ثمَّ
 * تُلحِقُ به ذيلًا يقرؤه الزائرُ لفظًا نبويًّا وليس من الروايةِ في شيء:
 *   • `fawaid-curated-` ١٢٢ و٣٥٢ و٥٧٤ و٧٩٦: «الرفق **ما وُضع** في شيء إلا
 *     زانه، **وما نُزع** من شيء إلا شانه» معزوًّا إلى «رواه مسلم» — ولفظُ
 *     مسلمٍ (٦٦٠٢ بترقيمِ النسخة): «إنَّ الرفقَ **لا يكون** في شيء إلا زانه
 *     **ولا يُنزع** من شيء إلا شانه»، فـ«في شيء إلا زانه» ثابتةٌ بنصِّها
 *     وما بينَ الشطرَينِ مبدَّلٌ.
 *   • `fawaid-curated-` ١٢٩ و٣٥٩ و٥٨١ و٨٠٣: «من حُرم الرفق حُرم الخير
 *     **كله**» معزوًّا إلى مسلمٍ — و«كله» ليست في النسخةِ ألبتّةَ (مسلم
 *     ٦٥٩٨ و٦٥٩٩ و٦٦٠٠: «مَنْ حُرِمَ الرِّفْقَ حُرِمَ الْخَيْرَ»).
 *   • `fawaid-curated-` ٠٨٧ و٣١٧ و٥٣٩ و٧٦١ و٩٨٣: «إياكم والجلوس على
 *     الطرقات **إلا أن تؤدوا حقها**» معزوًّا إلى البخاريِّ — وصدرُه لفظُه
 *     بعينِه (٢٤٦٥)، وعجزُه تلخيصٌ لا لفظ: «فَإِذَا أَبَيْتُمْ إِلاَّ
 *     الْمَجَالِسَ فَأَعْطُوا الطَّرِيقَ حَقَّهَا».
 *
 * وأفلتت الثلاثُ من البواباتِ كلِّها — ومنها ٣٦ نفسُها — لأنَّ ٣٦ تنظرُ إلى
 * **ما قبلَ** النافذةِ الثابتة، وهذه عللٌ **بعدَها**؛ ولأنَّ نافذةَ ٣٦ ثمانُ
 * كلماتٍ فلا تنعقدُ في لفظٍ قصيرٍ كـ«من حُرم الرفق حُرم الخير».
 *
 * فالفحصُ يسألُ: نافذةُ أربعِ كلماتٍ ثابتةٌ بنصِّها في المعزوِّ إليه، **ولا
 * تحملُها إلا خمسةُ أحاديثَ فأقلّ** (⇐ لفظُ روايةٍ بعينِها لا عبارةٌ
 * مطَّردة)، **وتقعُ في ذيلِ وحدتِها** (الباقي بعدَها ستُّ كلماتٍ فأقلّ ⇐
 * فالباقي دعوى لفظٍ لا انتقالٌ إلى كلامِ المحرِّر) ⇒ فحقُّ ذلك الباقي أن
 * يكونَ من الحديثِ الحاملِ للنافذةِ نفسِه، ولو باختصارٍ (`isSubsequenceLoose`).
 *
 * ⚠️ **وثلاثةُ قيودٍ لولاها لأسقطَ الفحصُ سليمًا** — انكشفت بمراجعةِ كلِّ
 * ساقطٍ فردًا فردًا (١٧ ساقطًا في أوَّلِ صياغة، ٥ منها إيجابٌ كاذب):
 *   (١) **قيدُ التمييز** (`≤ ٥` أحاديثَ تحملُ النافذة): بدونِه تنعقدُ
 *       النافذةُ على عبارةٍ مطَّردةٍ كـ«أبي بكر رضي الله» فيسقطُ
 *       `fawaid-curated-1055` وهو كلامُ محرِّرٍ في جمعِ القرآنِ لا دعوى لفظ.
 *   (٢) **قيدُ الذيل** (`≤ ٦` كلماتٍ باقية): بدونِه يسقطُ `-009` و`-019`
 *       و`-012` — وكلُّها لفظٌ صحيحٌ تامٌّ يعقبُه شرحُ المحرِّرِ بفاصلةٍ
 *       («…وهو يحسن الظن بالله، **فحسن الظن عند الموت من علامات…**»).
 *   (٣) **حصرُ التتابعِ في حاملِ النافذةِ وحدَه** لا في النسخةِ كلِّها:
 *       ستُّ كلماتٍ متفرِّقةً تُوجَدُ في حديثٍ طويلٍ ما بالمصادفة، فلو فُتِّش
 *       عنها في ٧٣٦٠ حديثًا لنجا العطبُ كلُّه (جُرِّب: ٠ ساقط).
 * وبهذه القيودِ أخرج الفحصُ **١٣ صفًّا بلا إيجابٍ كاذبٍ واحدٍ** من ٢١٩٠ سجلًّا.
 *
 * ج-٣٠٤ — **وقوبل حدّاه**: حدُّ التمييزِ رُفِع من ≤٥ أحاديثَ إلى ≤١٠ فلم يتغيَّرْ
 * شيءٌ (٠ فرقًا) ⇒ لا عطبَ تحتَه. وحدُّ الذيلِ رُفِع من ≤٦ كلماتٍ إلى ≤٨ فسقطَ
 * **صفٌّ واحدٌ وهو إيجابٌ كاذب**: `fawaid-curated-012` — «صلاة الجماعة أفضل من
 * صلاة الفذ بسبع وعشرين درجة**، ففيها تظهر وحدة الأمة ويُضاعف الأجر بمشاركة
 * المسلمين**» ومصدرُه يُخصِّصُ اللفظَ («واللفظ لمسلم») ويسوقُ لفظَ البخاريِّ
 * (٦٤٥) بحرفِه — فالثمانيةُ الباقيةُ **شرحُ محرِّرٍ موصولٌ بفاصلةٍ**، لا دعوى
 * لفظٍ. **فحدُّ الستِّ هو الفارقُ بين دعوى اللفظِ والانتقالِ إلى كلامِ المحرِّر**،
 * ورفعُه يُلغي القيدَ الثانيَ من القيودِ الثلاثةِ أعلاه أصلًا.
 *
 * ⚠️ `\b` **لا تنعقدُ بعدَ حرفٍ عربيٍّ** في JS (الحروفُ العربيةُ ليست `\w`)،
 * فحدُّ الكلمةِ هنا `(?![ء-ي])` لا `\b` — وبها انعقد القطعُ عندَ «، وهذا».
 */
const EDITORIAL_JOINT = /[؛:«»—…().]|،\s*(?=[وف]?(?:هذا|هذه|هو|هي)(?![ء-ي]))/;
const strictJoined = strictWords.map((hs) => hs.map((w) => w.join(" ")));
