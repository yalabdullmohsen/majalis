// ───── ٤٥) دعوى «ثبت في السنة الصحيحة» على تخريجٍ لا صحيحَ فيه ولا درجةَ معه ─────

/**
 * ج-٣٠١: خمسةُ صفوفٍ (`fawaid-curated-` ٩٩، ٣٢٩، ٥٥١، ٧٧٣، ٩٩٥ — نصٌّ واحدٌ
 * منسوخٌ خمسًا) نصُّها «حق الولد على والده أن يحسن اسمه ويحسن تربيته… **كما
 * ثبت في السنة الصحيحة.**» و`source` كلُّه «**رواه البيهقي**» — لا صحيحَينِ
 * ولا درجةَ مذكورة، وشعبُ الإيمانِ يجمعُ الصحيحَ والضعيفَ معًا. فالسجلُّ
 * يَحكمُ بالصحّةِ وحدَه بلا مستندٍ في حقلِه.
 *
 * **وبرهانُ العُرفِ من الملفِّ نفسِه إحصائيٌّ لا اجتهاديّ**: من ٢٧٨ سجلًّا
 * يحملُ هذه الدعوى، ٢٧٣ مصدرُها الصحيحانِ أو تخريجٌ معه درجةٌ صريحة — وهذه
 * الخمسةُ وحدَها شذَّت. 🔑 **وأخرجَ الفحصُ صفَّينِ زائدَينِ لم يبلغْهما المسحُ
 * اليدويُّ لأنَّه لم يتجاوزْ `fawaid-curated-seed.ts`**: `seed-fawaid-158`
 * («رواه الطبراني») و`seed-fawaid-263` («رواه الدارمي») — بلا درجةٍ وفيهما
 * الدعوى نفسُها، فعُومِلا بعينِ المعاملة. فحُذفت الجملةُ ولم تُخترَعْ درجةٌ (تصحيحُ حديثٍ حكمٌ
 * شرعيٌّ لا يُنشَأ في دورةِ تدقيق).
 *
 * وهو **مكمِّلٌ للفحصِ ١٧ لا مكرِّرٌ له**: ذاك ينظرُ إلى مصدرٍ يُصرِّحُ بأنَّ
 * اللفظَ موقوفٌ أو غيرُ مخرَّج، وهذا ينظرُ إلى مصدرٍ صحيحِ الصورةِ **خالٍ من
 * الدرجة**.
 */
const GRADE_WORD = /صحيح|صحّح|صحح|حسن|حسّن|ضعيف|ضعّف|متفق عليه/;
const SAHIHAYN_SRC = /البخاري|مسلم|متفق عليه|الصحيحين|الصحيحَين/;
const ungradedSunnaClaim = [...FAWAID_CURATED_SEED, ...SEED_FAWAID].filter((f) => {
  if (!/ثبت في السنة الصحيحة/.test(f.text)) return false;
  const src = f.source ?? "";
  if (!/^(رواه|أخرجه)/.test(src)) return false;
  return !SAHIHAYN_SRC.test(src) && !GRADE_WORD.test(src);
});
assert(
  ungradedSunnaClaim.length === 0,
  "لا سجلَّ يَدَّعي «ثبت في السنة الصحيحة» وتخريجُه ليس من الصحيحَينِ ولا درجةَ معه",
  ungradedSunnaClaim.map((f) => `${f.id}: ${f.source}`).join(" | ")
);

// ── ٤٦) دعوى «متفق عليه» على لفظٍ يفارقُ الصحيحَ الآخرَ في كلمةٍ داخلَه ──

/**
 * ج-٣٠٦: **ثقبٌ في الفحصِ ٣٢ نفسِه أخرجَه عطبُ ج-٣٠٥ ولم يُسَدَّ حينَه**:
 * الفحصُ ٣٢ يُعفي السجلَّ إن وُجدت نافذتُه في الصحيحِ الآخرِ **متتابعةً
 * بفجواتٍ غيرِ محدودةٍ** (`isSubsequenceLoose`) — والفجوةُ غيرُ المحدودةِ
 * تمسحُ **كلَّ الحديثِ بإسنادِه**، فتلتقطُ كلماتِ النافذةِ متفرِّقةً على
 * مئاتِ الكلماتِ فتشهدُ باتفاقٍ لا وجودَ له. فأفلتَ منه عطبانِ حيّانِ عالجَهما
 * ج-٣٠٥ **باليدِ لا بالبوابة**: «الإيمان بضعٌ **وستون** شعبة» (البخاريُّ ٩
 * وحدَه، ولفظُ مسلمٍ الأولُ ١٥٢ «بضعٌ **وسبعون**») و«**كل** مولود يولد على
 * الفطرة» (البخاريُّ ١٣٨٥ وحدَه، ولفظُ مسلمٍ «**ما من** مولود **إلا** يولد»).
 *
 * فهذا الفحصُ يُعيدُ السؤالَ نفسَه بمقابلةٍ **كلمةً كلمةً**: النافذةُ (خمسُ
 * كلماتٍ) ثابتةٌ بنصِّها المتتابعِ في أحدِ الصحيحَينِ، ولا شاهدَ لها في الآخرِ
 * **بفجوةٍ لا تزيدُ على أربعِ كلماتٍ داخلَ حديثٍ واحد** ⇒ فاللفظُ منفردٌ،
 * فدعوى «متفق عليه» عليه بلا تخصيصٍ خطأٌ. والعلاجُ عندَ السقوطِ هو علاجُ
 * ج-٢٩٠ نفسُه: **تخصيصُ اللفظِ لصاحبِه** لا نفيُ الاتفاقِ على الأصل.
 *
 * ⚠️ **وثلاثةُ قيودٍ قوبل كلٌّ منها بحدِّه فبرهنَ على لزومِه** (مسابرُ مؤقَّتةٌ
 * حُذفت بعد الفراغ، على ٢٨٠٦ سجلًّا):
 *   (١) **حدُّ الفجوةِ أربعٌ**: بفجوةِ ٢ سقطَ **٢٧ صفًّا كلُّها إيجابٌ كاذب** —
 *       اعتراضُ الراوي («حتى يحبَّ لأخيه **أو قال لجاره** ما يحبُّ لنفسه»
 *       مسلمٌ ١٧٠) وزيادةُ مسلمٍ في «خيرٌ لك **من أن يكون لك** حمرُ النعم»؛
 *       وبفجوةِ ٨ النتيجةُ هي هي (صفٌّ واحدٌ) ⇒ فالأربعُ أضبطُ حدٍّ يمسكُ
 *       الفرقَ في كلمةٍ ولا يُسقِطُ اختلافَ روايةٍ.
 *   (٢) **النافذةُ داخلَ المقتبسِ وحدَه** إن كان في النصِّ «»: بلا هذا القيدِ
 *       سقطَ `seed-fawaid-257` إيجابًا كاذبًا — نافذتُه «**قال** المسلم من سلم
 *       المسلمون» تعبرُ الحدَّ بين كلامِ المحرِّرِ («قال ﷺ:») واللفظِ، و«قال»
 *       تتقدَّمُ اللفظَ في البخاريِّ (١٠) لأنَّ إسنادَه ينتهي بها، ولا تتقدَّمُه
 *       في مسلمٍ (١٦٢) — وهو عينُ ثقبِ الفحصِ ٣٠ في ج-٣٠٤.
 *   (٣) **روايةُ الشكِّ لا تُحتَجُّ بها للاتفاق**: شاهدٌ فيه «أو» بين عددَين
 *       («بضعٌ وسبعون **أو** بضعٌ وستون») مردودٌ — إذ الشكُّ ليس لفظًا يُعزى.
 *       وهذا القيدُ **لا يُغيِّرُ النتيجةَ على السجلّاتِ اليومَ** (قوبل: صفرُ
 *       فرقٍ)، لأنَّ حدَّ الفجوةِ كفى في الحالتَين — وبقاؤه لأنَّه **يضيِّقُ
 *       الإعفاءَ لا يوسِّعُه**، فيحرسُ ما يُضافُ لاحقًا (سَنَنُ ج-٣٠٤).
 *
 * وخرجَ به من ٢٨٠٦ سجلًّا صفٌّ حيٌّ واحدٌ عُولج في هذه الدورةِ: `seed-fawaid-272`
 * — مصدرُه «واللفظ للبخاري (٦٠٤٠)» ونصُّه «فيحبه جبريل **ثم ينادي في أهل
 * السماء**… ثم يوضع له القبول **في الأرض**» وهما لفظُ **مسلمٍ** (٦٧٠٥)، ولفظُ
 * البخاريِّ «**فينادي جبريلُ** في أهل السماء… في **أهل** الأرض» — فرُدَّ النصُّ
 * إلى لفظِ البخاريِّ الذي خصَّصَه مصدرُه، بحرفِه من نسخةِ المستودع.
 */
const NUM_WORD = /^(?:واحد|اثن|ثلاث|اربع|خمس|ست|سبع|ثمان|تسع|عشر|عشرون|ثلاثون|اربعون|خمسون|ستون|سبعون|ثمانون|تسعون|مائ|الف|بضع)/;
const AGREE_MAX_GAP = 4;
/** أشاهدٌ للاتفاقِ في الصحيحِ الآخر: النافذةُ متتابعةٌ بفجواتٍ محدودةٍ، وليست روايةَ شكٍّ */
const agreementWitness = (win: string[], hadith: string[]) => {
  for (let s = 0; s < hadith.length; s++) {
    if (hadith[s] !== win[0]) continue;
    let i = 1;
    let j = s + 1;
    let gap = 0;
    while (j < hadith.length && i < win.length) {
      if (hadith[j] === win[i]) i++;
      else if (++gap > AGREE_MAX_GAP) break;
      j++;
    }
    if (i < win.length) continue;
    const span = hadith.slice(s, j);
    const doubted = span.includes("او") && span.filter((w) => NUM_WORD.test(w)).length >= 2;
    if (!doubted) return true;
  }
  return false;
};
const soleLafzWordByWord = [...FAWAID_CURATED_SEED, ...SEED_FAWAID].filter((f) => {
  const src = f.source ?? "";
  if (!/متفق عليه/.test(src)) return false;
  if (REJECTED.test(f.text) || REJECTED.test(src)) return false;
  const quoted = [...f.text.matchAll(/«([^»]+)»/g)].map((m) => m[1]);
  const segments = (quoted.length ? quoted : [f.text]).map((t) =>
    normStrict(t).split(" ").filter(Boolean).map(bareConj)
  );
  for (const w of segments) {
    for (let i = 0; i + 5 <= w.length; i++) {
      const win = w.slice(i, i + 5);
      const inB = conjCorpus[0].includes(win.join(" "));
      const inM = conjCorpus[1].includes(win.join(" "));
      if (inB === inM) continue;
      const other = inB ? 1 : 0;
      if (conjWordsOf[other].some((h) => agreementWitness(win, h))) continue;
      if (specifiesOwner(src, inB ? 0 : 1)) continue;
      return true;
    }
  }
  return false;
});
