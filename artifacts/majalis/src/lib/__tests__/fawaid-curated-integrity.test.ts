// ─────────────── ١٩) دعوى «متفق عليه» على لفظٍ منفردٍ بإحدى النسختَين ───────────────

/**
 * ثلاثةُ نصوصٍ (ج-٢٩٠) كان `source` فيها «**متفق عليه**» أو «رواه البخاري
 * ومسلم» ولفظُها في نسختَي المستودعِ **عند أحدِهما وحدَه**: «ما يصيب المسلم
 * من نصب ولا وصب…» لفظُ البخاريِّ ٥٦٤١ ولفظُ مسلمٍ سواه («ما من مصيبة يصاب
 * بها المسلم…»)، و«إذا اشتكى منه عضو تداعى له سائر الجسد» لفظُ مسلمٍ ٦٥٨٦
 * ولفظُ البخاريِّ ٦٠١١ «إذا اشتكى عضوًا تداعى له سائر جسدِه» — و`author_name`
 * في السجلِّ الثاني «صحيح البخاري» فوقَ ذلك. ودعوى الاتفاقِ على لفظٍ منفردٍ
 * تُوهمُ الزائرَ أنَّه يجدُه في الموضعَينِ معًا.
 *
 * والمقابلةُ بالنوافذِ لا بالنصِّ كلِّه: نصُّ السجلِّ يخلطُ لفظَ الروايةِ
 * بصياغةٍ تحريريّةٍ فلا يُطابقُ حرفيًّا، فتُؤخذُ **كلُّ** نوافذِ ستِّ كلماتٍ
 * متتاليةٍ منه وتُطلَبُ في النسختَين. ⚠️ **وخطوةُ النافذةِ ليست تفصيلًا
 * اقتصاديًّا**: بخطوةِ ٣ أَسقطَ الفحصُ حديثَ العودِ الهنديِّ إيجابًا كاذبًا،
 * لأنَّ لفظَ مسلمٍ يوافقُه ابتداءً من الكلمةِ الثانيةِ («عَلَيْكُنَّ» مكانَ
 * «عَلَيْكُمْ») فأفلتت النافذةُ الموافقةُ بينَ خطوتَين. والشرطُ **متساهلٌ عمدًا**:
 * لا يسقطُ السجلُّ إلّا إذا وُجدت له نافذةٌ في إحداهما و**لم توجدْ ولا نافذةٌ
 * واحدةٌ** في الأخرى — فاختلافُ لفظَينِ متَّفقٍ عليهما في كلمةٍ لا يُسقطُه،
 * والسجلُّ التحريريُّ الذي لا لفظَ روايةٍ فيه لا يدخلُ الفحصَ أصلًا.
 */
const AGREED_SRC = /متفق عليه|البخاري ومسلم/;
const windowsOf = (s: string, size = 6, step = 1) => {
  const w = normHadith(s).split(" ");
  const out: string[] = [];
  for (let i = 0; i + size <= w.length; i += step) out.push(w.slice(i, i + size).join(" "));
  return out;
};
const falseAgreement = [...FAWAID_CURATED_SEED, ...SEED_FAWAID].filter((f) => {
  const src = f.source ?? "";
  if (!AGREED_SRC.test(src)) return false;
  if (REJECTED.test(f.text) || REJECTED.test(src)) return false;
  // مصدرٌ يُصرِّحُ بصاحبِ اللفظِ («واللفظ للبخاري…»، «ولمسلم بلفظ: …») لا يَدَّعي
  // اتفاقًا على اللفظِ نفسِه، وإنَّما على أصلِ الحديث — وهو الصوابُ لا الخلل
  if (/بلفظ|واللفظ/.test(src)) return false;
  const wins = windowsOf(f.text);
  if (!wins.length) return false;
  const inB = wins.some((w) => corpus[0].includes(w));
  const inM = wins.some((w) => corpus[1].includes(w));
  return inB !== inM;
});
assert(
  falseAgreement.length === 0,
  "لا سجلَّ يَدَّعي «متفق عليه» ولفظُه في نسختَي المستودعِ عند أحدِهما وحدَه",
  falseAgreement.map((f) => `${f.id}: ${f.text.slice(0, 50)}`).join(" | ")
);

