/** يقبل عنواناً مجرداً أو زوجاً [عنوان، ملخص تعريفي موجز]. */
/** يقبل عنواناً أو [عنوان، ملخص] أو [عنوان، ملخص، متن موجز]. */
function lessons(prefix: string, items: (string | [string, string] | [string, string, string])[]): DarsItem[] {
  return items.map((item, i) => {
    if (!Array.isArray(item)) return { id: `${prefix}-${i + 1}`, title: item };
    const [title, summary, body] = item;
    return {
      id: `${prefix}-${i + 1}`,
      title,
      ...(summary ? { summary } : {}),
      ...(body ? { body } : {}),
    };
  });
}

