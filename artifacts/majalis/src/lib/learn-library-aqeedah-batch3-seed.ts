const byId = new Map(AQEEDAH_BATCH3_LESSONS.map((l) => [l.id, l]));

export function isAqeedahBatch3Slug(slug: string): slug is AqeedahSeedSlug {
  return (AQEEDAH_BATCH3_SEED_SLUGS as readonly string[]).includes(slug);
}

export function getSeedLessonsForSlug(slug: string): AqeedahSeedLesson[] {
  if (!isAqeedahBatch3Slug(slug)) return [];
  return AQEEDAH_BATCH3_LESSONS.filter((l) => l.categorySlug === slug);
}

export function getSeedLessonById(id: string): AqeedahSeedLesson | null {
  return byId.get(id) ?? null;
}

export function seedLessonCountForSlug(slug: string): number {
  return getSeedLessonsForSlug(slug).length;
}
