/** يزيل الذيل الآلي المكرر من نصوص الفوائد عند العرض — لا يغيّر المصدر. */
const FAWAID_BOILERPLATE = [
  /—\s*فليُلزم المسلم العمل بما علم(?:\s*والدعوة إليه)?\.?/gu,
  /—\s*فليُلزم المسلم العمل بما\.?/gu,
  /فليُلزم المسلم العمل بما علم(?:\s*والدعوة إليه)?\.?/gu,
  /والدعوة إليه\.?/gu,
  /وهذا مما يستحق من المسلم أن يتأمله ويأخذ به في سلوكه وعبادته\.?/gu,
  /وهذا من فوائد التدبر في كتاب الله والعمل بما فيه\.?\s*كما دلّ عليه الكتاب والسنة\.?/gu,
  /وهذا من هدي النبي ﷺ الذي يجب معرفته والعمل به\.?\s*كما ثبت في السنة الصحيحة\.?/gu,
  /وهذا أصل في الاعتقاد عند أهل السنة والجماعة\.?\s*يُستحضر في التعليم بلا غلو\.?/gu,
  /وهذا أصل يُسترشد به في فهم الأحكام الشرعية\.?\s*يُراجع في كتب الفقه المعتمدة\.?/gu,
  /،?\s*وهذا أصل يُسترشد به في فهم الأحكام الشرعية وتطبيقها\.?/gu,
  /،?\s*وهذا من هدي النبي ﷺ الذي يجب على المسلم معرفته والعمل به\.?/gu,
  /،?\s*وهذا من أصول الاعتقاد التي يُبنى عليها إيمان المسلم وعمله\.?/gu,
  /،?\s*وهذا من آداب طلب العلم وأصوله التي يُرجى بها نفع العلم\.?/gu,
  /وهذا من آداب الإسلام(?:\s*التي تُجمّل المسلم وتُقربه من ربه)?\.?/gu,
  /،\s*التي تُجمّل المسلم وتُقربه من ربه\.?/gu,
  /وهذا من مكارم الأخلاق التي أمر بها الشرع\.?/gu,
  /كما ثبت في السنة الصحيحة\.?/gu,
  /كما دلّ عليه الكتاب والسنة\.?/gu,
  /فحفظه وقراءته من أعظم القربات وأيسر طرق نيل الأجر/gu,
  /وهذا يُقرأ بضابط العلم والعمل[^.]*\.?/gu,
  /وهذا يقرأ بضابط العلم والعمل[^.]*\.?/gu,
  /وهذه فائدة تعليمية[^.]*\.?/gu,
  /وهي فائدة (?:تعليمية|تربوية|تذكيرية|محررة)[^.]*\.?/gu,
  /وهي فائدة[^.]*\.?/gu,
  /،?\s*وأن محبة النبي ﷺ (?:تظهر|تُصان)[^.]*\.?/gu,
  /،?\s*وأن العلم(?:\s+النافع)?[^.]*\.?/gu,
  /يُستحضر للعمل لا لمجرد الحفظ\.?/gu,
];

export function stripFawaidBoilerplate(text: string): string {
  let value = text.trim();
  for (const pattern of FAWAID_BOILERPLATE) {
    value = value.replace(pattern, "").trim();
  }
  return value.replace(/\s{2,}/g, " ").replace(/\s+([.،؛])/g, "$1").trim();
}
