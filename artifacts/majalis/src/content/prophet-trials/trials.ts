export function filterByProphet(prophetSlug: string): ProphetTrial[] {
  const slug = prophetSlug.trim().toLowerCase();
  if (!slug) return [];
  return PROPHET_TRIALS.filter((t) => t.prophetSlug === slug);
}

export function getProphetTrial(id: string): ProphetTrial | undefined {
  return PROPHET_TRIALS.find((t) => t.id === id);
}
